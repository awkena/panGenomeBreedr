#' Query Genotypes for Specific Variant IDs
#' 
#' Extracts complete genotype call records along with specified variant metadata properties 
#' for an explicit vector list of unique variant identifiers. Automatically resolves 
#' and unpacks internal array-packed list formats seamlessly into standard wide columns.
#' 
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' @param variant_ids A character vector of unique variant identifiers to look up (e.g., \code{c("SNP_Chr05_75104557")}).
#' @param variant_id_col A character value specifying the primary key column name for variant IDs. 
#'   Defaults to \code{"variant_id"}.
#' @param variants_table A character value specifying the name of the variants reference table view. 
#'   Defaults to \code{"variants"}.
#' @param genotypes_table A character value specifying the name of the genotype call data table view. 
#'   Defaults to \code{"genotypes"}.
#' @param meta_data A character vector of metadata columns (e.g., \code{"chrom"}, \code{"pos"}, \code{"ref"}) 
#'   to include from the variants table. If \code{NULL}, returns all available schema fields.
#' 
#' @return A data frame containing mapped metadata tracking columns alongside individual sample genotype 
#'   calls formatted in a structured variants-by-samples matrix.
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the database pipeline
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#' 
#' # Extract all sample genotypes for an explicit list of target marker strings
#' target_markers <- c("INDEL_Chr05_75104541", "SNP_Chr05_75104557")
#' marker_matrix <- query_genotypes(con = con, 
#'                                  variant_ids = target_markers,
#'                                  meta_data = c("chrom", "pos", "ref", "alt", "variant_type"))
#' 
#' # Safely close out the database connection
#' disconnect_local_db(con)
#' }
#' 
#' @import DBI
#' @export
query_genotypes <- function(
  con,
  variant_ids,
  variant_id_col = "variant_id",
  variants_table = 'variants',
  genotypes_table = 'genotypes',
  meta_data = NULL
) {
  # Prevent execution if no variant IDs are provided
  if (length(variant_ids) == 0) {
    warning("The 'variant_ids' vector is empty. No query was executed.")
    return(data.frame())
  }

  # Verify the active database connection
  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Check if required tables exist in DB
  all_tables <- DBI::dbListTables(con)
  if (!(variants_table %in% all_tables) || !(genotypes_table %in% all_tables)) {
    stop(
      "The specified variants or genotypes table does not exist in the database."
    )
  }

  if (is.null(meta_data)) {
    meta_data <- DBI::dbListFields(con, variants_table)
  } else {
    meta_data <- unique(c(variant_id_col, meta_data))
  }

  # Construct safe comma-separated column names for metadata and genotypes
  meta_cols_sql <- paste0("v.", meta_data, collapse = ", ")

  gt_cols <- DBI::dbListFields(con, genotypes_table)
  gt_data_cols <- setdiff(gt_cols, c(variant_id_col, "chrom", "pos"))
  gt_cols_sql <- paste0("g.", gt_data_cols, collapse = ", ")

  # Dynamically build '?' placeholders for parameterized DB querying
  placeholders <- paste(rep("?", length(variant_ids)), collapse = ", ")
  params <- as.list(variant_ids)

  sql <- sprintf(
    "
    SELECT %s, %s 
    FROM %s v 
    JOIN %s g ON v.%s = g.%s 
    WHERE v.%s IN (%s) 
    ORDER BY v.chrom, v.pos",
    meta_cols_sql,
    gt_cols_sql,
    variants_table,
    genotypes_table,
    variant_id_col,
    variant_id_col,
    variant_id_col,
    placeholders
  )

  res <- DBI::dbGetQuery(con, sql, params = params)

  if (nrow(res) == 0) {
    warning("No data found for the provided variant IDs.")
    return(data.frame())
  }

  if ("pos" %in% colnames(res)) {
    res$pos <- as.integer(res$pos)
  }

  # Parse array-packed genotypes if they are stored structurally within a 'calls' list
  if ("calls" %in% gt_data_cols && length(gt_data_cols) == 1) {
    parsed_list <- res$calls

    sample_names <- NULL
    if ("metadata" %in% all_tables) {
      sample_metadata <- DBI::dbGetQuery(
        con,
        "SELECT lib FROM metadata ORDER BY array_index ASC"
      )
      if (ncol(sample_metadata) > 0) sample_names <- sample_metadata[[1]]
    }

    if (
      is.null(sample_names) || length(sample_names) != length(parsed_list[[1]])
    ) {
      sample_names <- paste0("Sample_", seq_len(length(parsed_list[[1]])))
    }

    gt_matrix <- do.call(rbind, parsed_list)
    colnames(gt_matrix) <- sample_names

    info_cols <- res[, setdiff(names(res), "calls"), drop = FALSE]
    result <- cbind(
      info_cols,
      as.data.frame(gt_matrix, stringsAsFactors = FALSE)
    )
    return(result)
  }

  return(res)
}




#' Count the Distribution of Variant Types in the Database
#' 
#' Queries the database to calculate a global summary of how many variants 
#' exist for each distinct structural classification type (e.g., SNP, INDEL).
#' 
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' 
#' @return A data frame containing two columns: \code{variant_type} (the structural 
#'   classification group name) and \code{n} (the total count of variants in that group).
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the database pipeline
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#' 
