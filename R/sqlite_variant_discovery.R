#' Get Variant Statistics from the Database
#' 
#' Computes summary statistics for variants across chromosomes, including total counts, 
#' genomic ranges (minimum and maximum positions), and optionally distinct annotated 
#' variant counts.
#' 
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' @param include_annotations A logical value indicating whether to include 
#'   statistics for the annotations table. Defaults to \code{TRUE}.
#' 
#' @return A data frame of variant statistics grouped by chromosome.
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the database
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#'
#' # Get variant statistics across all chromosomes
#' stats_df <- variant_stats(con, include_annotations = TRUE)
#'
#' # Safely close the connection
#' disconnect_local_db(con)
#' }
#'
#' @import DBI
#' @export
variant_stats <- function(con, include_annotations = TRUE) {
  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Extract base statistics from the variants table (counts, min/max pos, unique IDs)
  variant_stats <- DBI::dbGetQuery(
    con,
    "
    SELECT
      chrom,
      COUNT(*) AS n_variants,
      MIN(pos) AS min_pos,
      MAX(pos) AS max_pos,
      COUNT(DISTINCT variant_id) AS n_unique_ids
    FROM variants
    GROUP BY chrom
    ORDER BY chrom
  "
  )

  if (include_annotations) {
    # Query for the count of distinct annotated variants using an inner join
    annotation_counts <- DBI::dbGetQuery(
      con,
      "
      SELECT chrom, COUNT(DISTINCT v.variant_id) AS n_annotated
      FROM variants v
      JOIN annotations a ON v.variant_id = a.variant_id
      GROUP BY chrom
    "
    )
    # Merge the annotation stats with the base stats
    variant_stats <- merge(
      variant_stats,
      annotation_counts,
      by = "chrom",
      all.x = TRUE
    )
    # Fill NA values with 0 for chromosomes lacking annotations
    variant_stats$n_annotated[is.na(variant_stats$n_annotated)] <- 0
  }

  return(variant_stats)
}




#' Summarize Variant Mutation Impacts Per Chromosome
#' 
#' Dynamically cross-tabulates and pivots the counts of functional mutation impact categories 
#' (e.g., HIGH, MODERATE, LOW, MODIFIER) across all chromosomes in the database.
#' 
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' 
#' @return A wide-format data frame where the first column is \code{chrom}, followed by 
#'   pivoted columns for each impact type (e.g., \code{impact_HIGH}, \code{impact_MODERATE}), 
#'   containing their respective mutation counts.
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the database
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#'
#' # Generate the wide-format impact profile matrix
#' impact_matrix <- variant_impact_summary(con)
#'
#' # Safely close the connection
#' disconnect_local_db(con)
#' }
#'
#' @import DBI
#' @export
variant_impact_summary <- function(con) {
  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Dynamically pivot the data by counting occurrences of each impact type per chromosome
  query <- "
    PIVOT (
      SELECT v.chrom, a.impact
      FROM annotations a
      JOIN variants v ON a.variant_id = v.variant_id
    )
    ON impact
    USING COUNT(*)
  "

  impact_wide <- DBI::dbGetQuery(con, query)
  # Format column names for clarity (e.g. HIGH -> impact_HIGH)
  col_names <- colnames(impact_wide)
  colnames(impact_wide)[-1] <- paste0("impact_", col_names[-1])

  # Replace any NA with 0 for chromosomes that might be missing a specific impact type entirely
  impact_wide[is.na(impact_wide)] <- 0

  return(impact_wide)
}




#' Name and Row Count for Each Table in the Database
#' 
#' Queries the active local database to instantly retrieve a list of all mounted 
#' tables along with their respective total row counts.
#' 
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' @return A data frame containing two columns: \code{table} (the table name) 
#'   and \code{n_rows} (the total number of rows in that table).
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the local database
#' my_db_folder <- "~/Desktop/curated_sorghum_variant_resource"
#' con <- connect_local_db(folder_path = my_db_folder)
#' 
#' # Get row counts for all mounted Parquet views
#' database_summary <- summarize_sqlite_tables(con)
#' 
#' # Safely close the connection
#' disconnect_local_db(con)
#' }
#'
#' @import DBI
#' @export
summarize_sqlite_tables <- function(con) {
  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Fetch all available tables
  tables <- DBI::dbListTables(con)

  # Retrieve and store the total number of rows for each table
  counts <- sapply(tables, function(tbl) {
    query <- sprintf("SELECT COUNT(*) FROM %s", tbl)
    DBI::dbGetQuery(con, query)[[1]]
  })

  summary_df <- data.frame(
    table = tables,
    n_rows = counts,
    row.names = NULL
  )

  return(summary_df)
}




#' Get the genomic range of a candidate gene using the Sobic ID from a gff file.
#' @param gene_name A character value indicating the Sobic ID of candidate gene.
#' @param gff_path A character value specifying the path to gff3 file. GZ compressed
#' files and URL file paths are acceptable.
#' @returns A list object of three components indicating the chromosome, start
#' and end coordinates of candidate gene.
#' @examples
#' \donttest{
#' # example code
#'
#' # Path to GFF3 file
#' gff_path <- "https://raw.githubusercontent.com/awkena/panGB/main/Sbicolor_730_v5.1.gene.gff3.gz"
#' gene_coord_gff(gene_name = "Sobic.005G213600",
#'                gff_path = gff_path)
#'
#' }
#' @export
#' @importFrom R.utils isUrl isGzipped gunzip
gene_coord_gff <- function(gene_name,
                           gff_path) {

  # Read GFF and extract gene coordinates
  if (R.utils::isUrl(gff_path)) {

    utils::download.file(gff_path,
                         destfile = file.path(tempdir(), basename(gff_path)))

    # Handle gzipped files by uncompressing before reading
    if (R.utils::isGzipped(file.path(tempdir(), basename(gff_path)))) {

      R.utils::gunzip(file.path(tempdir(), basename(gff_path)),
                      destname = file.path(tempdir(), 'my_gff.gff3'),
                      overwrite = TRUE,
                      remove = TRUE)

      gff <- utils::read.delim(file.path(tempdir(), "my_gff.gff3"),
                               comment.char = "#",
                               header = FALSE,
                               sep = "\t")
    } else {

      gff <- utils::read.delim(file.path(tempdir(), basename(gff_path)),
                               comment.char = "#",
                               header = FALSE,
                               sep = "\t")

    }

    # Ensure tempdir contents are deleted on exit
    on.exit({
      contents <- list.files(tempdir(),
                             full.names = TRUE,
                             recursive = TRUE,
                             all.files = TRUE,
                             include.dirs = TRUE)
      unlink(contents, recursive = TRUE, force = TRUE)
    }, add = TRUE)

  } else if (R.utils::isGzipped(gff_path)) {

    R.utils::gunzip(gff_path,
                    destname = file.path(dirname(gff_path), 'my_gff.gff3'),
                    overwrite = TRUE,
                    remove = TRUE)

    gff <- utils::read.delim(file.path(dirname(gff_path), 'my_gff.gff3'),
                             comment.char = "#",
                             header = FALSE,
                             sep = "\t")
  } else {

    gff <- utils::read.delim(gff_path,
                             comment.char = "#",
                             header = FALSE,
                             sep = "\t")
  }

  # Assign standard column names based on the GFF format specifications
  colnames(gff) <- c("seqid", "source", "type", "start", "end", "score", "strand",
                     "phase", "attributes")
  # Filter to strictly grab gene annotations
  genes <- gff[gff$type == "gene", ]
  # Extract the clean Gene Name from the semicolon-delimited attributes column
  genes$gene_name <- sub(".*Name=([^;]+).*", "\\1", genes$attributes)

  # Find the matching coordinates for the specified candidate gene
  gmatch <- genes[genes$gene_name == gene_name, ]
  if (nrow(gmatch) == 0) stop("Gene not found in GFF.")
  if (nrow(gmatch) > 1) warning("Multiple matches found; using the first match.")

  list(chrom = gmatch$seqid[1],
       start = as.integer(gmatch$start[1]),
       end   = as.integer(gmatch$end[1]))
}





