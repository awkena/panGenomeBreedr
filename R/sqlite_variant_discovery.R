#' Query Genomic Data Tables by Coordinate Range
#' 
#' Extracts structural genomic data chunks from a target virtual view based on 
#' chromosome, coordinate windows, and gene identification filters. Automatically 
#' parses and scales underlying list-packed genotype vectors into clear sample columns 
#' when hitting the genotypes engine.
#' 
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' @param table_name A character value specifying the target view to query. 
#'   Must be one of \code{"variants"}, \code{"annotations"}, or \code{"genotypes"}.
#' @param chrom A character value specifying the target chromosome name (e.g., \code{"Chr05"}).
#' @param start Integer. Optional start coordinate for the target window region.
#' @param end Integer. Optional end coordinate for the target window region.
#' @param gene_name A character value indicating the specific Sobic gene model ID. 
#'   Utilized explicitly when subsetting the \code{"annotations"} layout.
#' 
#' @return A data frame containing the targeted genomic records. For the \code{"genotypes"} 
#'   table, it returns individual samples unpacked directly into intuitive wide columns.
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Spin up the database pipeline
#' con <- connect_local_db("~/Desktop/curated_sorghum_variant_resource")
#' 
#' # Extract functional functional annotations inside a candidate locus region
#' annota_region <- query_db(con = con, chrom = "Chr05", start = 75104537, 
#'                           end = 75106403, table_name = "annotations", 
#'                           gene_name = "Sobic.005G213600")
#'                           
#' # Extract matrix genotypes within the exact same coordinates window
#' gt_region <- query_db(con = con, chrom = "Chr05", start = 75104537, 
#'                       end = 75106403, table_name = "genotypes")
#'                       
#' # Safely close out resources
#' disconnect_local_db(con)
#' }
#'
#' @import DBI
#' @export
query_db <- function(
  con,
  table_name = c("variants", "annotations", "genotypes"),
  chrom,
  start = NULL,
  end = NULL,
  gene_name = NULL
) {
  table_name <- match.arg(table_name)

  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Check if table exists
  all_tables <- DBI::dbListTables(con)
  if (!(table_name %in% all_tables)) {
    stop(sprintf("Table '%s' does not exist in the database.", table_name))
  }

  # ---  Annotations ---
  if (table_name == "annotations") {
    # Create an inner join across the annotations and variants table to filter by chrom and pos
    sql <- "
      SELECT a.*, v.chrom, v.pos
      FROM annotations a
      JOIN variants v ON a.variant_id = v.variant_id
      WHERE v.chrom = ?"

    params <- list(chrom)

    if (!is.null(start) && !is.null(end)) {
      sql <- paste(sql, "AND v.pos BETWEEN ? AND ?")
      params <- append(params, list(start, end))
    }

    # Filter by gene_name directly in SQL
    if (!is.null(gene_name)) {
      sql <- paste(sql, "AND a.gene_name = ?")
      params <- append(params, list(gene_name))
    }

    sql <- paste(sql, "ORDER BY v.pos")
    result <- DBI::dbGetQuery(con, sql, params = params)

    return(result)
  }

  # --- Genotypes ---
  if (table_name == "genotypes") {
    # Dynamically pull columns to safely support both wide and array-packed 'calls' storage formats
    gt_cols <- DBI::dbListFields(con, "genotypes")
    gt_data_cols <- setdiff(gt_cols, c("variant_id", "chrom", "pos"))
    gt_cols_sql <- paste0("g.", gt_data_cols, collapse = ", ")

    sql <- sprintf(
      "
      SELECT g.variant_id, g.chrom, g.pos, v.variant_type, v.ref, v.alt, %s
      FROM genotypes g
      JOIN variants v ON g.variant_id = v.variant_id
      WHERE g.chrom = ?",
      gt_cols_sql
    )

    params <- list(chrom)

    if (!is.null(start) && !is.null(end)) {
      sql <- paste(sql, "AND g.pos BETWEEN ? AND ?")
      params <- append(params, list(start, end))
    }

    sql <- paste(sql, "ORDER BY g.pos")
    result <- DBI::dbGetQuery(con, sql, params = params)

    if (nrow(result) == 0) {
      return(result)
    }

    # Unpack the array 
    if ("calls" %in% gt_data_cols && length(gt_data_cols) == 1) {

      parsed_list <- result$calls

      sample_names <- NULL

      # Retrieve sample names from metadata
      if ("metadata" %in% all_tables) {
        sample_metadata <- DBI::dbGetQuery(
          con,
          "SELECT lib FROM metadata ORDER BY array_index ASC"
        )

        # Safely extract the first column (assuming it holds the library/sample name)
        if (ncol(sample_metadata) > 0) {
          sample_names <- sample_metadata[[1]]
        }
      }

      if (
        is.null(sample_names) ||
          length(sample_names) != length(parsed_list[[1]])
      ) {
        sample_names <- paste0("Sample_", seq_len(length(parsed_list[[1]])))
      }

      # Reconstruct the matrix to hold all sample calls instantly
      gt_matrix <- do.call(rbind, parsed_list)
      colnames(gt_matrix) <- sample_names

      # Combine the metadata columns with the expanded genotype matrix
      info_cols <- result[, setdiff(names(result), "calls"), drop = FALSE]
      result <- cbind(
        info_cols,
        as.data.frame(gt_matrix, stringsAsFactors = FALSE)
      )
    }
    return(result)
  }

  # --- Variants ---
  # Directly pull and optionally filter variant metadata
  sql <- "
    SELECT * FROM variants v
    WHERE v.chrom = ?"

  params <- list(chrom)

  if (!is.null(start) && !is.null(end)) {
    sql <- paste(sql, "AND v.pos BETWEEN ? AND ?")
    params <- append(params, list(start, end))
  }

  sql <- paste(sql, "ORDER BY v.pos")
  result <- DBI::dbGetQuery(con, sql, params = params)
 
  return(result)
}




#' Extract Variants Based on Functional Mutation Impact
#' 
#' Queries the database to extract variants filtered by their functional impact severity 
#' classification (HIGH, MODERATE, LOW, or MODIFIER) following snpEff conventions. 
#' Optional chromosome and coordinate range windows can be added to narrow down targets.
#' 
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' @param impact_level A character vector specifying the variant impact types to retain. 
#'   Allowed classifications are \code{"HIGH"}, \code{"MODERATE"}, \code{"LOW"}, and \code{"MODIFIER"}.
#' @param chrom A character value specifying the chromosome name (e.g., \code{"Chr05"}).
#' @param start Integer. Optional start coordinate for the genomic region.
#' @param end Integer. Optional end coordinate for the genomic region.
#' 
#' @return A data frame of variants showing their predicted functional impact details 
#'   and positional coordinates.
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the database
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#' 
#' # Extract high-impact variant lines inside a targeted coordinates locus window
#' high_impact_vars <- query_by_impact(con = con,
#'                                     impact_level = "HIGH",
#'                                     chrom = "Chr05",
#'                                     start = 75104537,
#'                                     end = 75106403)
#' 
#' # Safely close out resources
#' disconnect_local_db(con)
#' }
#' 
#' @import DBI
#' @export
query_by_impact <- function(
  con,
  impact_level = c("HIGH", "MODERATE", "LOW", "MODIFIER"),
  chrom = NULL,
  start = NULL,
  end = NULL
) {
  # Validate the active database connection
  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Intersect with allowed options to sanitize the impact levels provided by the user
  allowed <- c("HIGH", "MODERATE", "LOW", "MODIFIER")
  impact_level <- intersect(toupper(impact_level), allowed)

  if (length(impact_level) == 0) {
    stop("No valid impact levels provided.")
  }

  # Dynamically build standard SQL IN placeholders
  placeholders <- paste(rep("?", length(impact_level)), collapse = ", ")

  # Join annotations and variants to retrieve requested variants safely via parameterization
  sql <- sprintf(
    "
    SELECT v.*, a.allele, a.annotation, a.impact, a.gene_name,
           a.gene_id, a.feature_type, a.feature_id, a.transcript_biotype,
           a.rank, a.HGVS_c, a.HGVS_p
    FROM variants v
    JOIN annotations a ON v.variant_id = a.variant_id
    WHERE a.impact IN (%s)",
    placeholders
  )
  params <- as.list(impact_level)

  if (!is.null(chrom)) {
    sql <- paste(sql, "AND v.chrom = ?")
    params <- append(params, list(chrom))

    if (!is.null(start) && !is.null(end)) {
      sql <- paste(sql, "AND v.pos BETWEEN ? AND ?")
      params <- append(params, list(start, end))
    }
  }

  sql <- paste(sql, "ORDER BY v.chrom, v.pos")
  result <- DBI::dbGetQuery(con, sql, params = params)

  return(result)
}




#' Compute Allele Frequencies for a Genotype Matrix
#' 
#' Calculates the reference (REF) and alternate (ALT) allele frequencies for an 
#' extracted wide matrix or data frame of variants by samples. Converts standard VCF 
#' genotype strings (e.g., "0/0", "0|1", "1|1") into numerical alternate allele dosages 
#' (0, 1, 2) to perform population-level frequency calculations.
#' 
#' @param gt A matrix or data frame containing variants (rows) across samples (columns), 
#'   including required variant identification and optional genomic coordinate metadata columns.
#' @param variant_id_col Character. The column name in \code{gt} matching unique variant identifiers. 
#'   Defaults to \code{"variant_id"}.
#' @param chrom_col Character. Optional column name in \code{gt} matching chromosome names. 
#'   Defaults to \code{NULL}.
#' @param pos_col Character. Optional column name in \code{gt} matching genomic positions. 
#'   Defaults to \code{NULL}.
#' 
#' @return A data frame containing unique variant identifiers, optional coordinate tracking columns, 
#'   calculated reference allele frequencies (\code{ref_af}), and alternate allele frequencies (\code{alt_af}).
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the database pipeline
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#' 
#' # Pull wide genotype records for a locus window range
#' gt_region <- query_db(con = con, chrom = "Chr05", start = 75104537, 
#'                       end = 75106403, table_name = "genotypes")
#' 
#' # Compute allele frequencies across all samples in the dataset
#' af_metrics <- calc_af(gt_region, variant_id_col = "variant_id", 
#'                       chrom_col = "chrom", pos_col = "pos")
#' 
#' # Safely close out the database connection
#' disconnect_local_db(con)
#' }
#' 
#' @export
calc_af <- function(gt,
                    variant_id_col = 'variant_id',
                    chrom_col = NULL,
                    pos_col = NULL){

  # if(!is.null(chrom)) chrom <- chrom
  # if(!is.null(pos)) pos <- pos

  # Exclude non-genotype mapping/reference columns
  sample_cols <- setdiff(colnames(gt), c(variant_id_col, chrom_col, pos_col))
  gt_matrix <- gt[, sample_cols, drop = FALSE]

  # Function to convert GT string to ALT dosage (0, 1, 2)
  parse_gt <- function(gt) {
    if (is.na(gt)) return(NA)
    if (gt %in% c("0|0", "0/0")) return(0)
    if (gt %in% c("0|1", "1|0", "0/1", "1/0")) return(1)
    if (gt %in% c("1|1", "1/1")) return(2)
    return(NA)  # For unexpected/missing codes
  }

  # Apply conversion function across all sample calls
  dosage_mat <- as.data.frame(apply(gt_matrix, c(1, 2), parse_gt),
                              stringsAsFactors = FALSE)

  # Calculate the alternate allele frequency based on dosages (sum of alt alleles / 2n samples)
  if(nrow(dosage_mat) > 1){
    alt_af <- rowMeans(sapply(dosage_mat, as.numeric), na.rm = TRUE) / 2
  } else{
    # Handle isolated single variant cases cleanly without rowMeans failing
    alt_af <- mean(sapply(dosage_mat, as.numeric), na.rm = TRUE) / 2
  }

  # Format the output data frame with IDs and calculated frequencies
  if(is.null(chrom_col) && is.null(pos_col) ) {

    result <- data.frame(variant_id = gt[, variant_id_col], ref_af = 1 - alt_af,
                         alt_af = alt_af)

  } else {

    result <- data.frame(gt[, c(variant_id_col, chrom_col, pos_col)],
                         ref_af = 1 - alt_af,
                         alt_af = alt_af)

  }

  return(result)

}




#' Filter Extracted Genotypes Based on Alternate Allele Frequency
#' 
#' Passes an extracted genotype matrix through calculation utilities to compute population-level 
#' allele frequencies, then subsets rows down to variants strictly falling between the 
#' specified minimum and maximum alternate allele frequency (MAF) thresholds.
#' 
#' @param gt A matrix or data frame containing variants (rows) across samples (columns), 
#'   including required variant identification and optional genomic coordinate metadata columns.
#' @param variant_id_col Character. The column name in \code{gt} matching unique variant identifiers. 
#'   Defaults to \code{"variant_id"}.
#' @param chrom_col Character. The column name in \code{gt} matching chromosome names. 
#'   Defaults to \code{"chrom"}.
#' @param pos_col Character. The column name in \code{gt} matching genomic positions. 
#'   Defaults to \code{"pos"}.
#' @param min_af Numeric. Minimum alternate allele frequency threshold for filtering. 
#'   Must fall between 0 and 1. Defaults to \code{0}.
#' @param max_af Numeric. Maximum alternate allele frequency threshold for filtering. 
#'   Must fall between 0 and 1. Defaults to \code{1}.
#' 
#' @return A data frame of variants passing the frequency thresholds, tracking their coordinates, 
#'   calculated reference allele frequencies (\code{ref_af}), and alternate allele frequencies (\code{alt_af}).
#' 
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the database pipeline
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#' 
#' # Pull wide genotype records for a locus window range
#' gt_region <- query_db(con = con, chrom = "Chr05", start = 75104537, 
#'                       end = 75106403, table_name = "genotypes")
#' 
#' # Filter out rare variants or monomorphic lines by restricting the alternate allele frequency window
#' filtered_vars <- filter_by_af(gt_region, variant_id_col = "variant_id", 
#'                               chrom_col = "chrom", pos_col = "pos", 
#'                               min_af = 0.05, max_af = 0.95)
#' 
#' # Safely close out the database connection
#' disconnect_local_db(con)
#' }
#' 
#' @export
filter_by_af <- function(gt,
                         variant_id_col = 'variant_id',
                         chrom_col = 'chrom',
                         pos_col = 'pos',
                         min_af = 0,
                         max_af = 1) {

  if (nrow(gt) == 0) {
    stop("No variant found in the genotype matrix.")
  }

  result <- calc_af(gt,
                    variant_id_col = variant_id_col,
                    chrom_col = chrom_col,
                    pos_col = pos_col)

  # Filter by allele frequency
  result <- result[result$alt_af >= min_af & result$alt_af <= max_af, ]

  return(result)
}





