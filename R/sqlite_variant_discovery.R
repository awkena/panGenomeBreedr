#' distribution of sorghum lines based on latitude and longitude coordinates. Points 
#' are dynamically colored by a user-specified metadata category and display scrollable, 
#' auto-formatted HTML tooltips containing all available metadata attributes.
#'
#' @param metadata A data frame containing sample metadata tracking information. Must include explicit 
#'   numeric \code{"lat"} and \code{"lon"} columns alongside the column specified in \code{color_by}.
#' @param color_by Character. The specific metadata column name used to group and assign discrete 
#'   color palette attributes to markers. Defaults to \code{"countryorigin"}.
#'
#' @return A \code{leaflet} map object (htmlwidget) displaying interactive geographic coordinate plots.
#'
#' @details
#' The function automatically strips out tracking lines containing missing spatial coordinates. 
#' Rather than hardcoding fixed tooltip categories, it dynamically extracts all non-coordinate metadata 
#' attributes present in the provided matrix, formatting them into clear, scrollable HTML popup panels 
#' for every marker.
#'
#' \strong{Dependency Note:} To keep core package requirements lean, \code{leaflet} 
#' and \code{tools} are configured as suggested package attachments. If they are absent from the local 
#' execution workspace, the script will halt cleanly and prompt appropriate installation commands.
#'
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Connect to the database pipeline
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#'
#' # Fetch passport metadata details for all accessions matching the resource
#' sample_metadata <- get_sample_metadata(con = con)
#'
#' # Generate an interactive geographic distribution plot colored by K-Means genetic cluster assignments
#' query_map_accessions(sample_metadata, color_by = "kmeans_cluster")
#' 
#' # Safely close out the database connection
#' disconnect_local_db(con)
#' }
#'
#' @export
query_map_accessions <- function(metadata, color_by = "countryorigin") {
  # Check if required external packages (leaflet and tools) exist 
  if (!requireNamespace("leaflet", quietly = TRUE)) {
    stop(
      "The 'leaflet' package is required to create interactive maps. ",
      "Please install it by running: install.packages('leaflet')",
      call. = FALSE
    )
  }
  if (!requireNamespace("tools", quietly = TRUE)) {
    stop(
      "The 'tools' package is required. Please run: install.packages('tools')",
      call. = FALSE
    )
  }

  # Check if coordinate columns exist and filter for complete cases
  if (!all(c("lat", "lon") %in% names(metadata))) {
    stop(
      "Metadata must contain 'lat' and 'lon' columns for geographic mapping."
    )
  }

  # Subset to samples with valid geographical coordinates
  plot_data <- metadata[!is.na(metadata$lat) & !is.na(metadata$lon), ]

  if (nrow(plot_data) == 0) {
    stop("No samples with valid latitude and longitude found in the metadata.")
  }

  # Isolate all columns except coordinates to construct interactive HTML popups
  meta_cols <- setdiff(names(plot_data), c("lat", "lon"))

  # HTML popups
  html_components <- lapply(meta_cols, function(col) {
    # Format feature titles via toTitleCase
    clean_title <- tools::toTitleCase(gsub("_", " ", col))
    ifelse(
      is.na(plot_data[[col]]),
      "",
      paste0("<b>", clean_title, ":</b> ", plot_data[[col]], "<br>")
    )
  })

  popup_info <- paste0(
    "<div style='font-family: Arial, sans-serif; font-size: 12px; max-height: 250px; overflow-y: auto;'>",
    do.call(paste0, html_components),
    "</div>"
  )

  # Generate dynamic color palette mapping for Leaflet markers based on the category chosen
  unique_vals <- unique(plot_data[[color_by]])

  pal <- leaflet::colorFactor(
    palette = "viridis",
    domain = unique_vals,
    na.color = "transparent"
  )

  # Construct the Leaflet map
  map <- leaflet::leaflet(data = plot_data) |>
    leaflet::addProviderTiles(leaflet::providers$CartoDB.Positron) |>
    leaflet::addCircleMarkers(
      lng = ~lon,
      lat = ~lat,
      radius = 5,
      color = ~ pal(plot_data[[color_by]]),
      stroke = FALSE,
      fillOpacity = 0.8,
      popup = popup_info,
      label = ~lib
    )

  return(map)
}






