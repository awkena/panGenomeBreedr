#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Query genotypes from the local database
#' local_genotypes <- fetch_genotypes_by_id(
#'   con = con_local,
#'   variant_ids = target_markers,
#'   meta_data = c('chrom', 'minor_allele_freq')
#' )
#' # print(local_genotypes[,1:6])
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
fetch_genotypes_by_id <- function(
  con = NULL,
  variant_ids,
  chrom = NULL,
  variant_id_col = "variant_id",
  variants_table = 'variants',
  genotypes_table = 'genotypes',
  meta_data = NULL,
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)

  if (connect_db_mode == 'online') {
    if (missing(variant_ids) || length(variant_ids) == 0) {
      warning(
        "The 'variant_ids' vector is empty. Returning empty data frame.",
        call. = FALSE
      )
      return(data.frame())
    }

    wants_all_data <- is.null(meta_data)
    user_requested_cols <- meta_data
    calculated_metric_cols <- c(
      "major_allele",
      "minor_allele",
      "major_allele_freq",
      "minor_allele_freq"
    )

    if (!wants_all_data) {
      user_db_cols <- setdiff(user_requested_cols, calculated_metric_cols)
      api_meta_cols <- unique(c(variant_id_col, "ref", "alt", user_db_cols))
      meta_str <- paste(api_meta_cols, collapse = ",")
    } else {
      meta_str <- NULL
    }

    ids_str <- paste(
      unique(trimws(variant_ids[!is.na(variant_ids) & nzchar(variant_ids)])),
      collapse = ","
    )

    query_params <- list(
      variant_ids = ids_str,
      variant_id_col = variant_id_col,
      variants_table = variants_table,
      genotypes_table = genotypes_table,
      meta_data = meta_str
    )

    if (!is.null(chrom)) {
      query_params$chrom <- paste(chrom, collapse = ",")
    }

    geno_res <- .api_fetch("/db/query_genotypes", query = query_params) # nocov

    if (is.null(geno_res) || nrow(geno_res) == 0) {
      warning("No data found for the provided variant IDs.", call. = FALSE)
      return(data.frame())
    }

    if (wants_all_data) {
      standard_metadata_fields <- c(
        variant_id_col,
        "variant_id",
        "chrom",
        "pos",
        "ref",
        "alt",
        "variant_type"
      )
      api_meta_cols <- intersect(colnames(geno_res), standard_metadata_fields)
      result_with_metrics <- append_locus_allele_metrics(
        geno_res,
        meta_data = api_meta_cols
      )
      return(result_with_metrics)
    } else {
      result_with_metrics <- append_locus_allele_metrics(
        geno_res,
        meta_data = api_meta_cols
      )
      sample_cols <- setdiff(colnames(geno_res), api_meta_cols)
      final_cols_to_return <- c(
        variant_id_col,
        user_requested_cols,
        sample_cols
      )
      final_cols_to_return <- intersect(
        final_cols_to_return,
        colnames(result_with_metrics)
      )
      return(result_with_metrics[, final_cols_to_return, drop = FALSE])
    }
  } else {
    if (
      is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)
    ) {
      stop("A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
           call. = FALSE)
    }

    user_requested_cols <- meta_data
    wants_all_data <- is.null(meta_data)

    if (length(variant_ids) == 0) {
      warning(
        "The 'variant_ids' vector is empty. No query was executed.",
        call. = FALSE
      )
      return(data.frame())
    }

    all_tables <- DBI::dbListTables(con)
    if (
      !(variants_table %in% all_tables) || !(genotypes_table %in% all_tables)
    ) {
      stop("The specified variants or genotypes table does not exist in the database.",
           call. = FALSE
      )
    }

    # Get chromosome number from ID if the user does not specify.
    if (is.null(chrom)) {
      extracted_chroms <- unique(regmatches(
        variant_ids,
        regexpr("Chr[0-9A-Za-z]+", variant_ids)
      ))
      if (length(extracted_chroms) > 0) {
        chrom <- extracted_chroms
      }
    }

    chrom_filter <- ""
    if (!is.null(chrom)) {
      chrom_sql <- paste(DBI::dbQuoteString(con, chrom), collapse = ", ")
      chrom_filter <- sprintf(
        "AND v.chrom IN (%s) AND g.chrom IN (%s)",
        chrom_sql,
        chrom_sql
      )
    }

    calculated_metric_cols <- c(
      "major_allele",
      "minor_allele",
      "major_allele_freq",
      "minor_allele_freq"
    )
    db_variant_fields <- DBI::dbListFields(con, variants_table)

    if (wants_all_data) {
      cols_to_fetch <- db_variant_fields
    } else {
      user_db_cols <- intersect(user_requested_cols, db_variant_fields)
      required_for_calc <- c("ref", "alt")
      cols_to_fetch <- unique(c(
        variant_id_col,
        user_db_cols,
        required_for_calc
      ))
    }

    meta_cols_sql <- paste0("v.", cols_to_fetch, collapse = ", ")
    gt_cols <- DBI::dbListFields(con, genotypes_table)
    gt_data_cols <- setdiff(gt_cols, c(variant_id_col, "chrom", "pos"))
    gt_cols_sql <- paste0("g.", gt_data_cols, collapse = ", ")

    # Chunking query sizes for optimization
    chunk_size <- 500
    id_chunks <- split(
      variant_ids,
      ceiling(seq_along(variant_ids) / chunk_size)
    )

    res_list <- list()

    for (chunk in id_chunks) {
      ids_sql <- paste(DBI::dbQuoteString(con, chunk), collapse = ", ")

      sql <- sprintf(
        "SELECT %s, %s 
         FROM %s v 
         JOIN %s g ON v.%s = g.%s AND v.chrom = g.chrom AND v.pos = g.pos 
         WHERE v.%s IN (%s) AND g.%s IN (%s) %s",
        meta_cols_sql,
        gt_cols_sql,
        variants_table,
        genotypes_table,
        variant_id_col,
        variant_id_col,
        variant_id_col,
        ids_sql,
        variant_id_col,
        ids_sql,
        chrom_filter
      )

      chunk_res <- DBI::dbGetQuery(con, sql)
      if (nrow(chunk_res) > 0) {
        res_list[[length(res_list) + 1]] <- chunk_res
      }
    }

    if (length(res_list) == 0) {
      warning("No data found for the provided variant IDs.", call. = FALSE)
      return(data.frame())
    }

    # Combine chunks
    res <- do.call(rbind, res_list)

    if ("pos" %in% colnames(res)) {
      res$pos <- as.integer(res$pos)
    }

    # Reorder
    if ("chrom" %in% colnames(res) && "pos" %in% colnames(res)) {
      res <- res[order(res$chrom, res$pos), ]
    }

    if ("calls" %in% colnames(res)) {
      parsed_list <- res$calls
      sample_names <- NULL
      if ("metadata" %in% all_tables) {
        sample_metadata <- DBI::dbGetQuery(
          con,
          "SELECT lib FROM metadata ORDER BY array_index ASC"
        )
        if (ncol(sample_metadata) > 0) {
          sample_names <- sample_metadata[[1]]
        }
      }
      if (
        is.null(sample_names) ||
          length(parsed_list) == 0 ||
          length(sample_names) != length(parsed_list[[1]])
      ) {
        sample_names <- paste0("Sample_", seq_len(length(parsed_list[[1]])))
      }

      # Unpack Matrix
      gt_matrix <- matrix(
        unlist(parsed_list, use.names = FALSE),
        nrow = length(parsed_list),
        byrow = TRUE
      )
      colnames(gt_matrix) <- sample_names

      info_cols <- res[, setdiff(names(res), "calls"), drop = FALSE]
      unpacked_res <- cbind(
        info_cols,
        as.data.frame(gt_matrix, stringsAsFactors = FALSE)
      )
    } else {
      unpacked_res <- res
    }

    result_with_metrics <- append_locus_allele_metrics(
      region_matrix = unpacked_res,
      meta_data = cols_to_fetch
    )

    if (wants_all_data) {
      return(result_with_metrics)
    } else {
      all_meta_cols <- c(db_variant_fields, calculated_metric_cols)
      sample_cols <- setdiff(colnames(result_with_metrics), all_meta_cols)
      final_cols_to_return <- c(
        variant_id_col,
        user_requested_cols,
        sample_cols
      )
      final_cols_to_return <- intersect(
        final_cols_to_return,
        colnames(result_with_metrics)
      )
      return(result_with_metrics[, final_cols_to_return, drop = FALSE])
    }
  }
}




#' Count the distribution of variant types in the database
#'
#' @description
#' This function counts the distribution of variant types (e.g., SNP, INDEL)
#' from either a local database connection or the online database.
#'
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#'   Required only when `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param variants_table Character. The name of the table containing variant
#'   metadata. Defaults to "variants".
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A data frame containing two columns: \code{variant_type} (the structural
#'   classification group name) and \code{n} (the total count of variants in that group).
#'
#' @examples
#' \donttest{
#' # --- Online Mode ---
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Count variant types from the online database
#' online_counts <- count_variant_types(connect_db_mode = 'online')
#' print(online_counts)
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Get the breakdown counts of SNPs vs INDELs
#' local_counts <- count_variant_types(con = con_local)
#' # print(local_counts)
#'
#' # Disconnnect at the end of the session.
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
count_variant_types <- function(con = NULL, variants_table = "variants", connect_db_mode = c('local', 'online')) {
  connect_db_mode <- match.arg(connect_db_mode)

  if (connect_db_mode == 'online') {
    params <- list(variants_table = variants_table)
    return(.api_fetch("/stats/variant_types", query = params)) # nocov
  } else {
    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop(
        "A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
        call. = FALSE
      )
    }

    cols <- DBI::dbListFields(con, variants_table)
    if (!"variant_type" %in% cols) {
      stop(
        sprintf("The '%s' table does not have a 'variant_type' column.", variants_table),
        call. = FALSE
      )
    }

    query <- sprintf("SELECT variant_type, COUNT(*) AS n FROM %s GROUP BY variant_type ORDER BY variant_type", variants_table)
    result <- DBI::dbGetQuery(con, query)
    return(result)
  }
}




#' Summarize functional annotations and impacts for a genomic region
#'
#' @description
#' This function queries variants within a specific genomic range and returns
#' summaries of SnpEff annotations and impact levels, cross-tabulated by
#' variant type. It can operate in 'local' or 'online' mode.
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param chrom Character. Chromosome name (e.g., "Chr05").
#' @param start Numeric. Start coordinate of the region.
#' @param end Numeric. End coordinate of the region.
#' @param annotations_table Character. Name of the annotations table. Defaults to "annotations".
#' @param variants_table Character. Name of the variants table. Defaults to "variants".
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A list object containing three summarized summary data frames:
#' \itemize{
#'   \item \code{annotation_summary}: Counts of distinct functional mutations grouped by type.
#'   \item \code{impact_summary}: Counts of predicted functional impacts grouped by type.
#'   \item \code{variant_type_totals}: Entire marker breakdown counts across the defined coordinate window.
#' }
#'
#' @examples
#' \donttest{
#' # --- Online Mode ---
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Get annotation summary from the online database
#' online_summary <- summarize_annotations(
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'online'
#' )
#' print(online_summary)
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Extract functional distribution summaries across a specific gene locus window
#' local_summary <- summarize_annotations(
#'   con = con_local,
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403
#' )
#' # print(local_summary)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
summarize_annotations <- function(
  con = NULL,
  chrom,
  start,
  end,
  annotations_table = "annotations",
  variants_table = "variants",
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)

  if (missing(chrom) || missing(start) || missing(end)) {
    stop(
      "You must provide 'chrom', 'start', and 'end' for the region summary.",
      call. = FALSE)
  }

  if (connect_db_mode == 'online') {
    query_params <- list(
      chrom = chrom, start = start, end = end,
      annotations_table = annotations_table, variants_table = variants_table
    )
    result <- .api_fetch("/stats/ann_summary", query = query_params, simplify = FALSE) # nocov

    if (is.null(result) || !is.data.frame(result$variant_type_totals) || nrow(result$variant_type_totals) == 0) {
      warning("No variants found in the specified region from the API.")
      return(list(annotation_summary = data.frame(), impact_summary = data.frame(), variant_type_totals = data.frame()))
    }

    result$annotation_summary <- as.data.frame(result$annotation_summary)
    result$impact_summary <- as.data.frame(result$impact_summary)
    result$variant_type_totals <- as.data.frame(result$variant_type_totals)
    return(result)

  } else {
    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop(
        "A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
        call. = FALSE)
    }

    ann_fields <- DBI::dbListFields(con, annotations_table)
    var_fields <- DBI::dbListFields(con, variants_table)
    required_ann <- c("variant_id", "annotation", "impact")
    required_var <- c("variant_id", "chrom", "pos", "variant_type")

    if (!all(required_ann %in% ann_fields)) stop("Annotations table must contain: ", paste(required_ann, collapse = ", "), call. = FALSE)
    if (!all(required_var %in% var_fields)) stop("Variants table must contain: ", paste(required_var, collapse = ", "), call. = FALSE)

    params <- list(chrom, start, end)

    sql_totals <- sprintf("SELECT variant_type, COUNT(*) AS total_variants FROM %s WHERE chrom = ? AND pos BETWEEN ? AND ? GROUP BY variant_type", variants_table)
    variant_type_totals <- DBI::dbGetQuery(con, sql_totals, params = params)

    sql_ann <- sprintf("SELECT a.annotation, v.variant_type, COUNT(*) AS count FROM %s a JOIN %s v ON a.variant_id = v.variant_id WHERE v.chrom = ? AND v.pos BETWEEN ? AND ? GROUP BY a.annotation, v.variant_type ORDER BY count DESC", annotations_table, variants_table)
    annotation_summary <- DBI::dbGetQuery(con, sql_ann, params = params)

    sql_impact <- sprintf("SELECT a.impact, v.variant_type, COUNT(*) AS count FROM %s a JOIN %s v ON a.variant_id = v.variant_id WHERE v.chrom = ? AND v.pos BETWEEN ? AND ? GROUP BY a.impact, v.variant_type ORDER BY count DESC", annotations_table, variants_table)
    impact_summary <- DBI::dbGetQuery(con, sql_impact, params = params)

    if (nrow(variant_type_totals) == 0) {
      warning(
        "No variants found in the specified region.",
        call. = FALSE)
      return(list(annotation_summary = data.frame(), impact_summary = data.frame(), variant_type_totals = data.frame()))
    }

    return(list(
      annotation_summary = annotation_summary,
      impact_summary = impact_summary,
      variant_type_totals = variant_type_totals
    ))
  }
}




#' Get sample metadata from the database
#'
#' @description
#' Retrieves sample metadata for the genotypes table from the database. It can operate in 'local' mode
#' to query a local database connection, or 'online' mode to fetch data from
#' the API. The function can return all metadata or filter by a specific column-value pair.
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param query_col Character. Optional metadata column name to filter by (e.g., `"countryorigin"`).
#'   If `NULL`, all metadata records are returned.
#' @param query_value Character or Numeric. The value to match within `query_col`.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A data frame containing the sample metadata records.
#'
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # --- Online Mode ---
#' # Retrieve all sample metadata from the online database
#' all_metadata_online <- fetch_accession_metadata(connect_db_mode = 'online')
#' print(all_metadata_online[1:3, 1:5])
#'
#' # Retrieve metadata for samples from Ghana from the online database
#' ghana_metadata_online <- fetch_accession_metadata(
#'   query_col = "countryorigin",
#'   query_value = "Ghana",
#'   connect_db_mode = 'online'
#' )
#' print(ghana_metadata_online[1:3, 1:5])
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Fetch metadata for all sorghum accessions originating from Ethiopia
#' ethiopia_metadata_local <- fetch_accession_metadata(
#'   con = con_local,
#'   query_col = "countryorigin",
#'   query_value = "Ethiopia"
#' )
#' # print(ethiopia_metadata_local[1:3, 1:5])
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
fetch_accession_metadata <- function(
  con = NULL,
  query_col = NULL,
  query_value = NULL,
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)

  if (connect_db_mode == 'online') {
    query_params <- list(query_col = query_col, query_value = query_value)
    return(.api_fetch("/db/metadata", query = query_params)) # nocov
  } else {
    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop(
        "A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
        call. = FALSE
      )
    }
    if (!("metadata" %in% DBI::dbListTables(con))) {
      stop(
        "Table 'metadata' not found in the database.",
        call. = FALSE
      )
    }
    if (!is.null(query_col)) {
      available_cols <- DBI::dbListFields(con, "metadata")
      if (!query_col %in% available_cols) {
        stop(
          sprintf("Column '%s' not found in the metadata table.", query_col),
          call. = FALSE
        )
      }
    }

    sql <- "SELECT * FROM metadata"
    params <- list()
    if (!is.null(query_col) && !is.null(query_value)) {
      sql <- paste0(sql, " WHERE ", query_col, " = ?")
      params <- list(query_value)
    }
    sql <- paste0(sql, " ORDER BY array_index ASC")

    result <- DBI::dbGetQuery(con, sql, params = params)
    return(result)
  }
}



#' Filter a genotype matrix by sample metadata
#'
#' @description
#' This function filters a genotype matrix based on sample metadata criteria,
#' allowing for selection of specific sub-populations. It can operate in
#' 'local' mode (querying a local DuckDB database for metadata) or 'online'
#' mode (fetching metadata from a remote API endpoint).
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param genotype_matrix A data frame or matrix where rows are variants and
#'   columns include variant metadata followed by sample genotypes.
#' @param genotype_start_col An integer specifying the column index where sample
#'   genotype calls begins.
#' @param filters A named list of metadata criteria to filter samples by.
#'   Names must match metadata schema columns, and values are the allowed entries.
#'   Example: \code{list(population = "Gates", countryorigin = c("Ethiopia", "Ghana", "Togo"))}
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A data frame containing the filtered genotype matrix with recalculated
#'   allele metrics for the sub-population. Returns an empty data frame if no
#'   samples match all combined criteria.
#' @examples 
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#' 
#' # Define filtering criteria
#' my_filters <- list(
#'   population = "Gates",
#'   countryorigin = c("Ethiopia", "Ghana", "Togo")
#' )
#'
#' # --- Online Mode ---
#' # Extract the full genotype matrix first for a genomic region from the online database
#' online_genotype_data_region <- fetch_table_region(
#'   table_name = "genotypes",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'online'
#' )
#'
#' # Get filtered genotypes matrix from online data
#' online_filtered_genotypes <- filter_genotypes_by_metadata(
#'   genotype_matrix = online_genotype_data_region,
#'   genotype_start_col = 11, # Assuming 11 is the correct start column for this data
#'   filters = my_filters,
#'   connect_db_mode = 'online'
#' )
#' print(head(online_filtered_genotypes))
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#' 
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Extract the full genotype matrix first for the genomic region from local DB
#' local_genotype_data_region <- fetch_table_region(
#'   con = con_local,
#'   table_name = "genotypes",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403
#' )
#'
#' # Get filtered genotypes matrix from local data
#' local_filtered_genotypes <- filter_genotypes_by_metadata(
#'   con = con_local,
#'   genotype_matrix = local_genotype_data_region,
#'   genotype_start_col = 11,
#'   filters = my_filters
#' )
#' # print(head(local_filtered_genotypes))
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @export
filter_genotypes_by_metadata <- function(
  con = NULL,
  genotype_matrix,
  genotype_start_col,
  filters,
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)

  # Validate matrix inputs
  if (!is.data.frame(genotype_matrix) && !is.matrix(genotype_matrix)) {
    stop("`genotype_matrix` must be a data frame or matrix.", call. = FALSE)
  }
  if (nrow(genotype_matrix) == 0) {
    warning("Input `genotype_matrix` is empty.", call. = FALSE)
    return(data.frame())
  }
  if (!is.numeric(genotype_start_col) || genotype_start_col <= 1) {
    stop(
      "`genotype_start_col` must be a numeric value greater than 1.",
      call. = FALSE
    )
  }

  # Validate the filters argument
  if (!is.list(filters) || is.null(names(filters))) {
    stop(
      "`filters` must be a named list. Example: list(population = 'Gates')",
      call. = FALSE
    )
  }

  if (connect_db_mode == 'online') {
    # Get sample metadata table using fetch_accession_metadata function
    full_metadata <- fetch_accession_metadata(connect_db_mode = 'online') 

    if (is.null(full_metadata) || nrow(full_metadata) == 0) {
      message("No metadata could be retrieved from the online database.")
      return(data.frame())
    }

    # Iteratively filter the metadata based on the provided list of criteria.
    filtered_metadata <- full_metadata
    for (col_name in names(filters)) {
      if (!col_name %in% colnames(filtered_metadata)) {
        warning(
          sprintf(
            "Column '%s' not found in online metadata. Skipping this filter.",
            col_name
          ),
          call. = FALSE
        )
        next
      }
      allowed_values <- filters[[col_name]]
      filtered_metadata <- filtered_metadata[
        filtered_metadata[[col_name]] %in% allowed_values,
        ,
        drop = FALSE
      ]
    }

    if (nrow(filtered_metadata) == 0) {
      message(
        "No samples found matching all combined metadata criteria in online mode."
      )
      return(data.frame())
    }

    sample_ids_to_keep <- if ("lib" %in% colnames(filtered_metadata)) {
      unique(filtered_metadata$lib)
    } else {
      warning(
        "Online metadata is missing the 'lib' column. Cannot identify samples to keep.",
        call. = FALSE
      )
      return(data.frame())
    }

    all_matrix_cols <- colnames(genotype_matrix)
    variant_meta_cols <- all_matrix_cols[seq_len(genotype_start_col - 1)]
    available_sample_cols <- intersect(sample_ids_to_keep, all_matrix_cols)

    if (length(available_sample_cols) == 0) {
      message(
        "None of the matching samples were found in the provided genotype matrix for online mode."
      )
      return(data.frame())
    }

    sub_population_matrix <- genotype_matrix[,
      c(variant_meta_cols, available_sample_cols),
      drop = FALSE
    ]

    base_meta_cols <- c(
      "variant_id",
      "chrom",
      "pos",
      "variant_type",
      "ref",
      "alt"
    )
    meta_for_recalc <- intersect(base_meta_cols, variant_meta_cols)

    final_result <- append_locus_allele_metrics(
      region_matrix = sub_population_matrix,
      meta_data = meta_for_recalc
    )
    return(final_result) # nocov
  } else {
    if (
      is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)
    ) {
      stop(
        "A valid 'con' object is required for 'local' mode. Please run connect_local_db() first."
      )
    }

    # Retrieve the table for metadata schema
    all_tables <- DBI::dbListTables(con)
    if (!"metadata" %in% all_tables) {
      stop(
        "The 'metadata' table does not exist in the local database.",
        call. = FALSE
      )
    }

    full_metadata <- DBI::dbGetQuery(con, "SELECT * FROM metadata")

    if (nrow(full_metadata) == 0) {
      message("The metadata table is empty.")
      return(data.frame())
    }

    # Iteratively filter the metadata based on the provided list of criteria
    filtered_metadata <- full_metadata
    for (col_name in names(filters)) {
      if (!col_name %in% colnames(filtered_metadata)) {
        warning(
          sprintf(
            "Column '%s' not found in metadata. Skipping this filter.",
            col_name
          ),
          call. = FALSE
        )
        next
      }
      allowed_values <- filters[[col_name]]
      filtered_metadata <- filtered_metadata[
        filtered_metadata[[col_name]] %in% allowed_values,
        ,
        drop = FALSE
      ]
    }

    if (nrow(filtered_metadata) == 0) {
      message("No samples found matching all combined metadata criteria.")
      return(data.frame())
    }

    sample_ids_to_keep <- if ("lib" %in% colnames(filtered_metadata)) {
      unique(filtered_metadata$lib)
    } else {
      warning(
        "Metadata is missing the 'lib' column. Cannot identify samples to keep.",
        call. = FALSE
      )
      return(data.frame())
    }

    all_matrix_cols <- colnames(genotype_matrix)
    variant_meta_cols <- all_matrix_cols[seq_len(genotype_start_col - 1)]
    available_sample_cols <- intersect(sample_ids_to_keep, all_matrix_cols)

    if (length(available_sample_cols) == 0) {
      message("None of the matching samples were found in the genotype matrix.")
      return(data.frame())
    }

    sub_population_matrix <- genotype_matrix[,
      c(variant_meta_cols, available_sample_cols),
      drop = FALSE
    ]

    base_meta_cols <- c(
      "variant_id",
      "chrom",
      "pos",
      "variant_type",
      "ref",
      "alt"
    )
    meta_for_recalc <- intersect(base_meta_cols, variant_meta_cols)

    result <- append_locus_allele_metrics(
      region_matrix = sub_population_matrix,
      meta_data = meta_for_recalc
    )
    return(result)
  }
}



#' Interactive geographic exploration of the samples
#'
#' @param metadata A data frame containing sample metadata tracking information. Must include explicit 
#'   numeric \code{"lat"} and \code{"lon"} columns alongside the column specified in \code{color_by}.
#' @param color_by Character. The specific metadata column name used to group and assign discrete 
#'   color palette attributes to markers. Defaults to \code{"countryorigin"}.
#'
#' @return A \code{leaflet} map object (htmlwidget) displaying interactive geographic coordinate plots.
#'
#' @examples 
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#' 
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#' 
#' # Establish a virtual connection to the offline database engine
#' con <- connect_local_db(folder_path = my_db_folder)
#'
#' # Fetch passport metadata details for all accessions matching the resource
#' sample_metadata <- fetch_accession_metadata(con = con)
#'
#' # Generate an interactive geographic distribution plot colored by countryorigin
#' plot_accession_map_result <- plot_accession_map(sample_metadata, color_by = "countryorigin")
#' print(plot_accession_map_result)
#' 
#' # Disconnect at the end of your session
#' disconnect_local_db(con)
#' }
#'
#' @export
plot_accession_map <- function(metadata, color_by = "countryorigin") {
  # Check if required external packages (leaflet and tools) exist 
  if (!requireNamespace("leaflet", quietly = TRUE)) {
    stop(
      "The 'leaflet' package is required to create interactive maps. ",
      "Please install it by running: install.packages('leaflet')",
      call. = FALSE
    )
  }
  if (!requireNamespace("tools", quietly = TRUE)) {
    stop(
      "The 'tools' package is required. Please run: install.packages('tools')",
      call. = FALSE
    )
  }

  # Validate color_by argument
  if (!color_by %in% names(metadata)) {
    stop(
      sprintf("The column specified for `color_by` ('%s') was not found in the metadata.", color_by),
      call. = FALSE)
  }

  # Check if coordinate columns exist and filter for complete cases
  if (!all(c("lat", "lon") %in% names(metadata))) {
    stop(
      "Metadata must contain 'lat' and 'lon' columns for geographic mapping.",
      call. = FALSE
    )
  }
  suppressWarnings({
    metadata$lat <- as.numeric(metadata$lat)
    metadata$lon <- as.numeric(metadata$lon)
  })
  # Subset to samples with valid geographical coordinates
  plot_data <- metadata[!is.na(metadata$lat) & !is.na(metadata$lon), ]

  if (nrow(plot_data) == 0) {
    stop(
      "No samples with valid latitude and longitude found in the metadata.",
      call. = FALSE
    )
  }

  # Isolate all columns except coordinates to construct interactive HTML popups
  meta_cols <- setdiff(names(plot_data), c("lat", "lon"))

  # HTML popups
  html_components <- lapply(meta_cols, function(col) {
    clean_title <- tools::toTitleCase(gsub("_", " ", col))
    ifelse(
      is.na(plot_data[[col]]),
      "",
      paste0("<b>", clean_title, ":</b> ", plot_data[[col]], "<br>")
    )
  })

  popup_info <- paste0(
    "<div style='font-family: Arial, sans-serif; font-size: 12px; max-height: 250px; overflow-y: auto;'>",
    do.call(paste0, html_components),
    "</div>"
  )

  # Create a color palette function based on the chosen column
  pal <- leaflet::colorFactor(
    palette = "viridis",
    domain = plot_data[[color_by]],
    na.color = "transparent"
  )

  plot_data$color_col <- pal(plot_data[[color_by]])

  # Construct the Leaflet map
  map <- leaflet::leaflet(data = plot_data) |>
    leaflet::addProviderTiles(leaflet::providers$CartoDB.Positron) |>
    leaflet::addCircleMarkers(
      lng = ~lon,
      lat = ~lat,
      radius = 5,
      color = ~color_col,
      stroke = FALSE,
      fillOpacity = 0.8,
      popup = popup_info,
      label = ~lib
    )

  return(map)
}





#' Plot variant hotspots
#'
#' @param variant_table Data frame containing basic variants
#' @param annotation_table Data frame containing annotations
#' @param region_start Numeric start position
#' @param region_end Numeric end position
#' @import ggplot2
#' @importFrom stats runif
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#' 
#' # Fetch variant and annotation data for a specific region from the online database
#' variants <- fetch_table_region(
#'   table_name = "variants",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'online'
#' )
#' 
#' annotations <- fetch_table_region(
#'   table_name = "annotations",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'online'
#' )
#' 
#' # Generate the variant hotspot plot
#' hotspot_plot <- plot_variant_hotspots(
#'   variant_table = variants,
#'   annotation_table = annotations
#' )
#' 
#' # Display the plot
#' print(hotspot_plot)
#' }
#' @export
#'
plot_variant_hotspots <- function(
  variant_table,
  annotation_table = NULL,
  region_start = NULL,
  region_end = NULL
) {
  pos <- y_pos <- impact <- variant_type <- NULL

  plot_df <- variant_table
  if (!"variant_type" %in% colnames(plot_df)) {
    plot_df$variant_type <- sub("_.*", "", plot_df$variant_id)
  }

  # Join and Deduplicate Annotations
  impact_levels <- c("HIGH", "MODERATE", "LOW", "MODIFIER", "UNKNOWN")

  if (
    !is.null(annotation_table) &&
      nrow(annotation_table) > 0 &&
      "impact" %in% colnames(annotation_table)
  ) {
    anno_sub <- annotation_table[, c("variant_id", "impact")]
    anno_sub$impact <- factor(
      anno_sub$impact,
      levels = impact_levels,
      ordered = TRUE
    )
    anno_sub <- anno_sub[order(anno_sub$impact, na.last = TRUE), ]
    anno_sub <- anno_sub[!duplicated(anno_sub$variant_id), ]

    plot_df <- merge(plot_df, anno_sub, by = "variant_id", all.x = TRUE)
    plot_df$impact <- as.character(plot_df$impact)
    plot_df$impact[is.na(plot_df$impact)] <- "UNKNOWN"
  } else {
    plot_df$impact <- "UNKNOWN"
  }

  plot_df$impact <- factor(plot_df$impact, levels = rev(impact_levels))

  # Extract start and stop postion from table if is null
  if (is.null(region_start)) {
    region_start <- min(plot_df$pos, na.rm = TRUE)
  }
  if (is.null(region_end)) {
    region_end <- max(plot_df$pos, na.rm = TRUE)
  }

  total_vars <- nrow(plot_df)
  snp_ct <- sum(plot_df$variant_type == "SNP", na.rm = TRUE)
  indel_ct <- sum(plot_df$variant_type == "INDEL", na.rm = TRUE)

  summary_text <- sprintf(
    "Total Unique Variants: %s  |  SNPs: %s  |  INDELs: %s",
    scales::comma(total_vars),
    scales::comma(snp_ct),
    scales::comma(indel_ct)
  )

  # Assigning base elevations to each impact level
  y_mapping <- c(
    "HIGH" = 4,
    "MODERATE" = 3,
    "LOW" = 2,
    "MODIFIER" = 1,
    "UNKNOWN" = 0.5
  )
  plot_df$base_y <- y_mapping[as.character(plot_df$impact)]

  # Add micro-jitter within lanes so points don't perfectly overlap
  set.seed(42)
  plot_df$y_pos <- plot_df$base_y +
    runif(nrow(plot_df), min = -0.25, max = 0.25)

  # Color Impact levels
  impact_colors <- c(
    "HIGH" = "#e11d48",
    "MODERATE" = "#f59e0b",
    "LOW" = "#3b82f6",
    "MODIFIER" = "#94a3b8",
    "UNKNOWN" = "#cbd5e1"
  )

  type_shapes <- c("SNP" = 21, "INDEL" = 24)

  # Plot
  p <- ggplot2::ggplot(plot_df, ggplot2::aes(x = pos, y = y_pos)) +
    ggplot2::geom_hline(
      yintercept = c(1, 2, 3, 4),
      color = "#f1f5f9",
      linewidth = 0.5
    ) +
    ggplot2::geom_hline(yintercept = 0, linewidth = 2, color = "#cbd5e1") +
    ggplot2::geom_segment(
      ggplot2::aes(xend = pos, yend = 0),
      color = "#dcdfe3",
      alpha = 0.3,
      linewidth = 0.4
    ) +
    ggplot2::geom_point(
      ggplot2::aes(fill = impact, shape = variant_type),
      size = 5,
      color = "black",
      stroke = 0.5,
      alpha = 0.7
    ) +
    # Manual setting of legends and mapping values
    ggplot2::scale_fill_manual(values = impact_colors, name = "Max Impact") +
    ggplot2::scale_shape_manual(values = type_shapes, name = "Variant Type") +
    ggplot2::scale_x_continuous(labels = scales::comma) +
    ggplot2::coord_cartesian(
      xlim = c(region_start, region_end),
      ylim = c(-0.1, 4.5)
    ) +
    ggplot2::theme_minimal(base_size = 14) +
    ggplot2::labs(
      title = "Genomic Variant Hotspots",
      subtitle = paste0(
        plot_df$chrom[1],
        ": ",
        scales::comma(region_start),
        " - ",
        scales::comma(region_end)
      ),
      caption = summary_text,
      x = "Genomic Position (bp)"
    ) +
    ggplot2::guides(
      fill = ggplot2::guide_legend(
        override.aes = list(shape = 21, size = 4),
        order = 1
      ),
      shape = ggplot2::guide_legend(
        override.aes = list(fill = "#fefefe14", size = 4, color = 'black'),
        order = 2
      ) # Modifyying legends
    ) +
    ggplot2::theme(
      axis.text.y = ggplot2::element_blank(),
      axis.title.y = ggplot2::element_blank(),
      panel.grid.major.y = ggplot2::element_blank(),
      panel.grid.minor.y = ggplot2::element_blank(),
      panel.grid.minor.x = ggplot2::element_blank(),
      panel.grid.major.x = ggplot2::element_line(
        color = "#e2e8f0",
        linetype = "dashed"
      ),

      legend.position = "right",
      legend.box = "vertical",
      legend.title = ggplot2::element_text(
        face = "bold",
        size = 10,
        color = "#475569"
      ),
      legend.text = ggplot2::element_text(size = 9, color = "#334155"),

      plot.title = ggplot2::element_text(
        face = "bold",
        size = 16,
        color = "#0f172a",
        hjust = 0.5
      ),
      plot.subtitle = ggplot2::element_text(
        color = "#64748b",
        size = 12,
        hjust = 0.5,
        margin = ggplot2::margin(b = 10)
      ),
      plot.caption = ggplot2::element_text(
        face = "bold",
        color = "#1e293b",
        size = 12,
        hjust = 1,
        margin = ggplot2::margin(t = 15)
      ),
      axis.title.x = ggplot2::element_text(
        face = "bold",
        color = "#475569",
        margin = ggplot2::margin(t = 10)
      )
    )

  return(p)
}





#' Compute Linkage Disequilibrium (LD) Metrics (R2 and D')
#'
#' @param df A data frame containing the genotype matrix. Must include a `variant_id`
#'   column and a genomic position column (e.g., 'pos', 'position').
#' @param target_variant_ids A character vector of target variant IDs. If provided,
#'   the function runs in "Targeted Mode". If `NULL` (default), it runs in
#'   "All-vs-All Mode".
#' @param genotype_start_col An integer specifying the column index where phased
#'   genotype calls (e.g., "0|0", "1|0") begin. Defaults to 7.
#'
#' @return A long-format data frame with the following columns:
#' \item{variant_1}{ID of the first variant in the pair.}
#' \item{variant1_position}{Genomic position of the first variant.}
#' \item{variant1_type}{Type of the first variant (SNP or INDEL).}
#' \item{variant_2}{ID of the second variant in the pair.}
#' \item{variant2_position}{Genomic position of the second variant.}
#' \item{variant2_type}{Type of the second variant (SNP or INDEL).}
#' \item{distance_bp}{Absolute physical distance in base pairs between the variants.}
#' \item{R2}{The squared correlation coefficient ($R^2$).}
#' \item{D_prime}{The normalized linkage disequilibrium coefficient ($D'$).}
#'
#' @export
#' @examples
#' \donttest{
#' # Mode 1: Compute full pairwise matrix landscape
#' 
#' # Get genotype matrix from the online database
#' query_geno <- panGenomeBreedr::fetch_table_region(
#' table_name = "genotypes",
#' chrom = "Chr03",
#' start = 79037682,
#' end = 79039091,
#' connect_db_mode = 'online'
#' )
#' 
#' full_ld <- calculate_LD(df = query_geno, target_variant_ids = NULL, genotype_start_col = 11)
#' print(head(full_ld))
#' 
#' # Mode 2: Targeted calculation panel for KASP marker vetting
#' target_variants <- c("INDEL_Chr03_79037682", "INDEL_Chr03_79037750", "SNP_Chr03_79039022")
#' targeted_panel <- calculate_LD(
#'   df = query_geno, 
#'   target_variant_ids = target_variants, 
#'   genotype_start_col = 11
#' )
#' print(head(targeted_panel))
#' }
calculate_LD <- function(
  df,
  target_variant_ids = NULL,
  genotype_start_col = 11
) {
  # Get position column
  pos_col_idx <- grep("pos", names(df), ignore.case = TRUE)
  if (length(pos_col_idx) == 0) {
    stop(
      "Could not find a physical position column (e.g., 'pos' or 'position') in your data frame."
    )
  }
  pos_col_name <- names(df)[pos_col_idx[1]]

  # Validate that all specified anchor variants exists
  if (!is.null(target_variant_ids)) {
    missing_anchors <- target_variant_ids[
      !(target_variant_ids %in% df$variant_id)
    ]
    if (length(missing_anchors) > 0) {
      stop(paste(
        "The following anchor variant ID(s) were not found in the dataframe:",
        paste(missing_anchors, collapse = ", ")
      ))
    }
  }

  variant_ids <- as.character(df$variant_id)
  num_variants <- length(variant_ids)

  variant_positions <- as.numeric(df[[pos_col_name]])
  variant_types <- ifelse(
    grepl("INDEL", variant_ids, ignore.case = TRUE),
    "INDEL",
    "SNP"
  )

  # Haplotypes Matrix Conversion 
  gt_data <- df[, genotype_start_col:ncol(df), drop = FALSE]
  haplotypes <- do.call(
    cbind,
    lapply(1:ncol(gt_data), function(i) {
      split_gt <- strsplit(as.character(gt_data[[i]]), "[|/]")
      h1 <- as.numeric(sapply(split_gt, `[`, 1))
      h2 <- as.numeric(sapply(split_gt, `[`, 2))
      cbind(h1, h2)
    })
  )
  rownames(haplotypes) <- variant_ids
  num_haplotypes <- ncol(haplotypes)

  master_results_list <- list()

  # compute full pairwise LD matrix if no target variants are specified.
  if (is.null(target_variant_ids)) {

    pair_counter <- 1
    for (i in 1:(num_variants - 1)) {
      anchor_id <- variant_ids[i]
      vec_Anchor <- haplotypes[anchor_id, ]
      p_Anchor <- sum(vec_Anchor) / num_haplotypes
      if (p_Anchor == 0 || p_Anchor == 1) {
        next
      }

      anchor_pos <- variant_positions[i]
      anchor_type <- variant_types[i]

      for (j in (i + 1):num_variants) {
        var_id <- variant_ids[j]
        vec_B <- haplotypes[var_id, ]
        p_B <- sum(vec_B) / num_haplotypes
        if (p_B == 0 || p_B == 1) {
          next
        }

        # Calculate  haplotype frequencies and the D statistic.
        P_AB <- sum(vec_Anchor == 1 & vec_B == 1) / num_haplotypes
        D <- P_AB - (p_Anchor * p_B)

        r2_val <- (D^2) / (p_Anchor * (1 - p_Anchor) * p_B * (1 - p_B))
        D_max <- ifelse(
          D >= 0,
          min(p_Anchor * (1 - p_B), (1 - p_Anchor) * p_B),
          min(p_Anchor * p_B, (1 - p_Anchor) * (1 - p_B))
        )
        dp_val <- abs(D) / D_max

        target_pos <- variant_positions[j]
        target_type <- variant_types[j]

    
        # Append results for the pair to the master list.
        master_results_list[[pair_counter]] <- data.frame(
          variant_1 = anchor_id,
          position_1 = anchor_pos,
          variant_type_1 = anchor_type,
          variant_2 = var_id,
          position_2 = target_pos,
          variant_type_2 = target_type,
          distance_bp = abs(target_pos - anchor_pos),
          R2 = round(r2_val, 5),
          D_prime = round(dp_val, 5),
          stringsAsFactors = FALSE
        )
        pair_counter <- pair_counter + 1
      }
    }

  # compute ld between defined varinats and entire varinats within the genomic region.
  } else {

    for (anchor_id in target_variant_ids) {
      vec_Anchor <- haplotypes[anchor_id, ]
      p_Anchor <- sum(vec_Anchor) / num_haplotypes
      if (p_Anchor == 0 || p_Anchor == 1) {
        warning(paste("Anchor variant", anchor_id, "is monomorphic. Skipping."))
        next
      }

      # Check for the current anchor variant.
      idx_A <- which(variant_ids == anchor_id)
      anchor_pos <- variant_positions[idx_A]
      anchor_type <- variant_types[idx_A]

      anchor_results <- list()

      for (j in 1:num_variants) {
        var_id <- variant_ids[j]
        if (var_id == anchor_id) {
          next
        }

        vec_B <- haplotypes[var_id, ]
        p_B <- sum(vec_B) / num_haplotypes
        if (p_B == 0 || p_B == 1) {
          next
        }

        P_AB <- sum(vec_Anchor == 1 & vec_B == 1) / num_haplotypes
        D <- P_AB - (p_Anchor * p_B)

        r2_val <- (D^2) / (p_Anchor * (1 - p_Anchor) * p_B * (1 - p_B))
        D_max <- ifelse(
          D >= 0,
          min(p_Anchor * (1 - p_B), (1 - p_Anchor) * p_B),
          min(p_Anchor * p_B, (1 - p_Anchor) * (1 - p_B))
        )
        dp_val <- abs(D) / D_max

        target_pos <- variant_positions[j]
        target_type <- variant_types[j]

        anchor_results[[var_id]] <- data.frame(
          variant_1 = anchor_id,
          position_1 = anchor_pos,
          variant_type_1 = anchor_type,
          variant_2 = var_id,
          position_2 = target_pos,
          variant_type_2 = target_type,
          distance_bp = abs(target_pos - anchor_pos),
          R2 = round(r2_val, 5),
          D_prime = round(dp_val, 5),
          stringsAsFactors = FALSE
        )
      }
      
      master_results_list[[anchor_id]] <- do.call(rbind, anchor_results)
    }
  }


  # combine all results into a single data frame.
  if (length(master_results_list) == 0) {
    return(data.frame(
      variant_1 = character(),
      position_1 = numeric(),
      variant_type_1 = character(),
      variant_2 = character(),
      position_2 = numeric(),
      variant_type_2 = character(),
      distance_bp = numeric(),
      R2 = numeric(),
      D_prime = numeric(),
      stringsAsFactors = FALSE
    ))
  }

  final_ld_df <- do.call(rbind, master_results_list)
  rownames(final_ld_df) <- NULL

  return(final_ld_df)
}




#' Generate Geodesic Landscape Plot and Extract Haploblock Data
#'
#' @param ld_df A long-format data frame of pairwise LD statistics containing 
#'   columns \code{variant_1}, \code{variant_2}, and the column matching \code{metric}.
#' @param query_db_geno A data frame with variant genotype metadata. Must include a
#'   \code{variant_id} column and a genomic position column (e.g., 'pos').
#' @param query_db_annot A data frame with variant annotation metadata. Must include
#'   \code{variant_id} and a functional \code{impact} column.
#' @param metric Character string. The linkage metric to visualize ("R2" or "D_prime").
#' @param target_variant_ids A character vector of variant IDs to highlight on the plot.
#' @param threshold Numeric. The minimum LD value to display. Pairs below this 
#'   value fade to white background spaces. Defaults to 0.2.
#' @param block_threshold Numeric. The threshold at which to group and isolate block variants. Defaults to 0.8.
#' @param show_variant_labels Logical. If TRUE (default), displays variant IDs above the spine.
#'
#' @param filled Logical. If `TRUE`, renders filled geodesic polygons. If `FALSE`
#'   (default), renders line-based trajectories.
#' @param palette_option Character string. The `viridis` color palette to use for
#'   mapping LD values these include: "magma", "plasma", "inferno", "viridis", "mako", "cividis", "rocket" and "turbo". Defaults to `"magma"`.
#' @return A structured \code{list} containing two named assets:
#' \itemize{
#'   \item \code{plot}: A ggplot object showing the geodesic LD landscape.
#'   \item \code{table}: A data frame where columns represent haploblocks, listing their constituent variants and impacts.
#' }
#' 
#' @import ggplot2
#' 
#' @export
#' @examples
#' \donttest{ 
#' query_annot <- panGenomeBreedr::fetch_table_region(
#' table_name = "annotations",
#' chrom = "Chr03",
#' gene_name = "Sobic.003G421300",
#' start = 79037682,
#' end = 79039091,
#' connect_db_mode = 'online'
#' )
#' 
#' query_geno <- panGenomeBreedr::fetch_table_region(
#' table_name = "genotypes",
#' chrom = "Chr03",
#' start = 79037682,
#' end = 79039091,
#' connect_db_mode = 'online'
#' )
#' 
#' # Compute your updated wide data containing distance tracking columns
#' ld_results <- calculate_LD(
#' df = query_geno,
#' target_variant_ids = NULL,
#' genotype_start_col = 11
#' )
#' 
#' # Generate the plot and table package
#' result <- plot_ld_geodesic(
#'   ld_df = ld_results, 
#'   query_db_geno = query_geno, 
#'   query_db_annot = query_annot,
#'   metric = "R2",
#'   target_variant_ids = c("INDEL_Chr03_79037889", "SNP_Chr03_79037855","SNP_Chr03_79037944"),
#'   threshold = 0.8, 
#'   block_threshold = 0.8
#' )
#'
#' # Access the plot
#' result$plot
#'
#' # Access the haploblock table
#' print(result$table)
#' }
plot_ld_geodesic <- function(
  ld_df,
  query_db_geno,
  query_db_annot,
  metric = "R2",
  threshold = 0.2,
  block_threshold = 0.8,
  show_variant_labels = TRUE,
  target_variant_ids = NULL,
  filled = FALSE,
  palette_option = "magma"
) {

  # Set global variables to null.
  value <- variant_1 <- variant_2 <- x <- y <- group <- linewidth_metric <- pos_mb <- y_anchor <- variant_id <- variant_type <- NULL

  # Obtain the position column map
  pos_col <- grep("pos", names(query_db_geno), ignore.case = TRUE, value = TRUE)
  if (length(pos_col) == 0) {
    stop("Could not find a genomic position column.")
  }

  map_info_raw <- data.frame(
    variant_id = as.character(query_db_geno$variant_id),
    pos = as.numeric(query_db_geno[[pos_col]]),
    stringsAsFactors = FALSE
  )

  map_info_raw <- map_info_raw[order(map_info_raw$pos), ]
  map_info_raw$pos_mb <- map_info_raw$pos / 1e6
  map_info_raw$variant_type <- ifelse(
    grepl("INDEL", map_info_raw$variant_id, ignore.case = TRUE),
    "INDEL",
    "SNP"
  )

  # Identify target variants
  map_info_raw$is_target <- FALSE
  if (!is.null(target_variant_ids) && length(target_variant_ids) > 0) {
    map_info_raw$is_target[
      map_info_raw$variant_id %in% target_variant_ids
    ] <- TRUE
  }

  ld_working <- ld_df
  names(ld_working)[names(ld_working) == "anchor_variant"] <- "variant_1"
  names(ld_working)[names(ld_working) == "target_variant"] <- "variant_2"
  names(ld_working)[names(ld_working) == metric] <- "value"

  ld_pairs <- subset(ld_working, value >= threshold)
  ld_pairs$p1 <- map_info_raw$pos_mb[match(
    ld_pairs$variant_1,
    map_info_raw$variant_id
  )]
  ld_pairs$p2 <- map_info_raw$pos_mb[match(
    ld_pairs$variant_2,
    map_info_raw$variant_id
  )]
  ld_pairs <- ld_pairs[!is.na(ld_pairs$p1) & !is.na(ld_pairs$p2), ]

  active_variant_ids <- unique(c(ld_pairs$variant_1, ld_pairs$variant_2))
  map_info <- map_info_raw[map_info_raw$variant_id %in% active_variant_ids, ]
  if (nrow(map_info) == 0) {
    stop("No variants meet the current threshold parameters.")
  }

  min_variant_x <- min(map_info$pos_mb)
  max_variant_x <- max(map_info$pos_mb)
  variant_span <- max_variant_x - min_variant_x
  if (variant_span == 0) {
    variant_span <- 0.001
  }

  # Identify haploblocks
  core_pairs <- subset(ld_pairs, value >= block_threshold)
  block_data_list <- list()

  if (nrow(core_pairs) > 0) {
    visited_variants <- c()
    block_counter <- 1

    for (m in 1:nrow(map_info)) {
      v_id <- map_info$variant_id[m]
      if (v_id %in% visited_variants) {
        next
      }

      linked_rows <- subset(core_pairs, variant_1 == v_id | variant_2 == v_id)
      if (nrow(linked_rows) == 0) {
        next
      }

      linked_partners <- unique(c(linked_rows$variant_1, linked_rows$variant_2))
      linked_partners <- sort(linked_partners)
      visited_variants <- c(visited_variants, linked_partners)

      impact_vec <- character(length(linked_partners))
      for (i in 1:length(linked_partners)) {
        impact_obs <- query_db_annot[
          query_db_annot$variant_id == linked_partners[i],
          'impact'
        ]
        impact_vec[i] <- if (length(unique(impact_obs)) == 1) {
          unique(impact_obs)
        } else {
          paste(unique(impact_obs), collapse = ' | ')
        }
      }

      block_df <- data.frame(
        variants = linked_partners,
        impacts = impact_vec,
        stringsAsFactors = FALSE
      )
      names(block_df) <- c(
        paste0("Block_", block_counter),
        paste0("Block_", block_counter, "_Impact_Level")
      )
      block_data_list[[block_counter]] <- block_df
      block_counter <- block_counter + 1
    }
  }

  final_block_table <- data.frame()
  if (length(block_data_list) > 0) {
    max_rows <- max(sapply(block_data_list, nrow))
    padded_dfs <- lapply(block_data_list, function(df) {
      if (nrow(df) < max_rows) {
        pad_df <- as.data.frame(matrix(
          NA,
          nrow = max_rows - nrow(df),
          ncol = ncol(df)
        ))
        names(pad_df) <- names(df)
        df <- rbind(df, pad_df)
      }
      return(df)
    })
    final_block_table <- do.call(cbind, padded_dfs)
  }

  # Polygon curve rendering logic
  geom_list <- list()
  if (nrow(ld_pairs) > 0) {
    for (i in 1:nrow(ld_pairs)) {
      row <- ld_pairs[i, ]
      x1 <- min(row$p1, row$p2)
      x2 <- max(row$p1, row$p2)
      mid <- (x1 + x2) / 2
      relative_span <- (x2 - x1) / variant_span

      steps <- seq(0, 1, length.out = 30)
      curve_left_x <- x1 + (mid - x1) * steps
      curve_left_y <- -relative_span * (1 - (1 - steps)^2)
      curve_right_x <- mid + (x2 - mid) * steps
      curve_right_y <- -relative_span * (1 - steps^2)

      if (filled) {
        coords_x <- c(curve_left_x, curve_right_x, x1)
        coords_y <- c(curve_left_y, curve_right_y, 0)
      } else {
        coords_x <- c(curve_left_x, curve_right_x)
        coords_y <- c(curve_left_y, curve_right_y)
      }

      geom_list[[i]] <- data.frame(
        x = coords_x,
        y = coords_y,
        group = i,
        value = row$value,
        linewidth_metric = row$value * 1.8
      )
    }
  }
  plot_geoms <- do.call(rbind, geom_list)

  plot_title <- if (filled) {
    "Geodesic Haplotype Topology"
  } else {
    "Geodesic Linkage Interaction Map"
  }

  plot_subtitle <- if (filled) {
    paste0(
      "Structural LD block characterization using ",
      tools::toTitleCase(palette_option),
      " topology projection"
    )
  } else {
    paste0(
      "Pairwise variant linkage resolution using ",
      tools::toTitleCase(palette_option),
      " trajectory projection"
    )
  }

  map_info <- map_info[order(map_info$is_target), ]

  label_data <- map_info
  label_data$y_anchor <- 0
  max_y_limit <- if (show_variant_labels) 1.5 else 0.1

  p <- ggplot()

  # Conditional Geometry Layer Selector (Arcs)
  if (filled) {
    p <- p +
      geom_polygon(
        data = plot_geoms,
        aes(x = x, y = y, group = group, fill = value),
        alpha = 0.35,
        color = NA
      )
  } else {
    p <- p +
      geom_path(
        data = plot_geoms,
        aes(
          x = x,
          y = y,
          group = group,
          color = value,
          linewidth = linewidth_metric
        ),
        alpha = 0.8,
        lineend = "round"
      ) +
      scale_linewidth_identity()
  }

  # base chromosome track line
  p <- p + geom_hline(yintercept = 0, color = "#1E293B", linewidth = 1.5)

  # Add Variant Labels if enabled
  if (show_variant_labels) {
    # Because label_data is now sorted, these colors map perfectly to the z-indexed rendering
    label_colors <- ifelse(label_data$is_target, "darkred", "#1E293B")
    segment_colors <- ifelse(label_data$is_target, "darkred", "grey50")
    segment_thickness <- ifelse(label_data$is_target, 0.6, 0.3)

    p <- p +
      ggrepel::geom_text_repel(
        data = label_data,
        aes(x = pos_mb, y = y_anchor, label = variant_id),
        direction = "x",
        nudge_y = 0.35,
        angle = 90,
        size = 2.8,
        fontface = "bold",
        color = label_colors,
        segment.color = segment_colors,
        segment.size = segment_thickness,
        segment.alpha = 0.8,
        max.overlaps = Inf,
        box.padding = 0.2,
        point.padding = 0.1
      )
  }

  # Add variant dots on the spine
  spine_colors <- ifelse(map_info$is_target, "darkred", "#1E293B")
  spine_stroke <- ifelse(map_info$is_target, 1.2, 0.5)

  p <- p +
    geom_point(
      data = map_info,
      aes(x = pos_mb, y = 0, shape = variant_type),
      size = 3.5,
      color = spine_colors,
      fill = "#E2E8F0",
      stroke = spine_stroke
    ) +
    scale_shape_manual(
      values = c("SNP" = 21, "INDEL" = 24),
      name = "Variant Type"
    )

  # Configure Dynamic Coloring Palette (Arcs Only)
  if (filled) {
    p <- p +
      scale_fill_viridis_c(
        option = palette_option,
        limits = c(0, 1),
        name = expression(R^2),
        direction = -1
      )
  } else {
    p <- p +
      scale_color_viridis_c(
        option = palette_option,
        limits = c(0, 1),
        name = expression(R^2),
        direction = -1
      )
  }

  # Final Canvas Formatting
  p <- p +
    scale_x_continuous(
      limits = c(
        min_variant_x - (variant_span * 0.05),
        max_variant_x + (variant_span * 0.05)
      ),
      labels = function(x) sprintf("%.4f", x),
      expand = c(0, 0)
    ) +
    scale_y_continuous(limits = c(-1.1, max_y_limit), expand = c(0, 0)) +
    theme_minimal(base_size = 11) +
    labs(
      title = plot_title,
      subtitle = plot_subtitle,
      x = "Genomic Position (Mb)",
      y = NULL
    ) +
    theme(
      panel.grid = element_blank(),
      axis.text.y = element_blank(),
      axis.title.y = element_blank(),
      axis.text.x = element_text(colour = 'black', size = 12),
      plot.title = element_text(
        face = "bold",
        size = 16,
        color = "#0F172A",
        hjust = 0.5
      ),
      plot.subtitle = element_text(color = "grey40", size = 12, hjust = 0.5),
      axis.title.x = element_text(
        face = "bold",
        margin = margin(t = 10),
        color = "#0F172A",
        size = 14
      ),
      legend.position = "right",
      legend.title = element_text(size = 9, face = "bold")
    )

  return(list(plot = p, table = final_block_table))
}





#' Append Locus Allele Metrics to Germplasm Genotype Matrix
#'
#' Computes major and minor allele states along with their respective gametic frequencies
#' for a targeted genomic window, appending these diversity metrics directly into the
#' matrix schema immediately following the variant metadata and preceding the accession columns.
#'
#' @param region_matrix A dataframe from the genotype table with calls.
#' @param ref_col A character string specifying the column name for the reference allele.
#'   Defaults to `"ref"`.
#' @param alt_col A character string specifying the column name for the alternative allele.
#'   Defaults to `"alt"`.
#' @param meta_data A character vector defining the baseline variant descriptor columns
#'   to anchor on the left flank of the matrix. Defaults to standard genomic coordinates.
#'
#' @return A modified genotype matrix data frame with allele frequencies and allele type
#'
#' @noRd
append_locus_allele_metrics <- function(
  region_matrix,
  ref_col = "ref",
  alt_col = "alt",
  meta_data = c("variant_id", "chrom", "pos", "ref", "alt", "variant_type")
) {
  meta_cols <- intersect(meta_data, names(region_matrix))
  sample_cols <- setdiff(names(region_matrix), meta_cols)

  if (length(sample_cols) == 0) {
    return(region_matrix)
  }

  # Extract genotype matrix
  mat <- as.matrix(region_matrix[, sample_cols, drop = FALSE])

  dosage <- matrix(NA_real_, nrow = nrow(mat), ncol = ncol(mat))

  dosage[mat %in% c("0|0", "0/0")] <- 0
  dosage[mat %in% c("0|1", "1|0", "0/1", "1/0")] <- 1
  dosage[mat %in% c("1|1", "1/1")] <- 2

  # Count alt alleles (dosage sum) and missing values
  sum_dosage <- rowSums(dosage, na.rm = TRUE)
  n_valid <- rowSums(!is.na(dosage))
  total_alleles <- n_valid * 2

  # Count of reference alleles (total alleles minus alt allele dosages)
  count_1 <- sum_dosage
  count_0 <- total_alleles - count_1

  # Vectorized major/minor allele assignment
  ref_vals <- region_matrix[[ref_col]]
  alt_vals <- region_matrix[[alt_col]]

  major_allele <- ifelse(count_0 >= count_1, ref_vals, alt_vals)
  minor_allele <- ifelse(count_0 < count_1, ref_vals, alt_vals)

  # Gametic allele frequencies
  safe_total <- ifelse(total_alleles == 0, 1, total_alleles)
  minor_allele_freq <- round(pmin(count_0, count_1) / safe_total, 5)
  major_allele_freq <- round(pmax(count_0, count_1) / safe_total, 5)

  region_matrix$major_allele <- major_allele
  region_matrix$minor_allele <- minor_allele
  region_matrix$major_allele_freq <- major_allele_freq
  region_matrix$minor_allele_freq <- minor_allele_freq

  # Reorder columns cleanly
  new_metrics <- c(
    "major_allele",
    "minor_allele",
    "major_allele_freq",
    "minor_allele_freq"
  )

  sample_cols_n <- setdiff(names(region_matrix), c(meta_cols, new_metrics))
  optimized_column_order <- c(meta_cols, new_metrics, sample_cols_n)

  return(region_matrix[, optimized_column_order, drop = FALSE])
}