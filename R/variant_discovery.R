#' Connect to the local offline database
#'
#' @description
#' Establishes a virtual connection to the offline database engine using DuckDB. 
#' It mounts the core pangenome-scale Parquet files .
#'
#' @param folder_path Character. The absolute or relative path to the directory
#'   containing the core database files (`genotypes_partitioned/`, `variants.parquet`,
#'   `metadata.parquet`, `annotations.parquet`) and optionally the `pcil/` extension directory.
#' @param max_memory Character. Maximum RAM DuckDB is allowed to utilize.
#'   Defaults to '"8GB"'. Adjust based on system constraints.
#' @param quiet Logical. If \code{TRUE}, suppresses console messages. Defaults to \code{FALSE}.
#'
#' @return A DBI connection object (`con`) linked to the virtual database.
#'
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#' 
#'
#' # Establish the connection
#' con <- connect_local_db(folder_path = my_db_folder, max_memory = "8GB")
#'
#' }
#'
#' @import DBI
#' @export
connect_local_db <- function(folder_path, max_memory = "8GB", quiet = FALSE) {
  
  # Confirm if the the unpartioned files for ...
  expected_files <- c(
    "variants.parquet",
    "metadata.parquet",
    "annotations.parquet"
  )

  for (f in expected_files) {
    full_path <- file.path(folder_path, f)
    if (!file.exists(full_path)) {
      stop(paste(
        "Critical file missing:",
        f,
        "\nPlease check your folder path:",
        folder_path
      ))
    }
  }
  
  # Check if partitioned genotypes directory exists
  geno_path <- file.path(folder_path, "genotypes_partitioned")
  if (!dir.exists(geno_path)) {
    stop(paste(
      "Critical directory missing: genotypes_partitioned",
      "\nPlease check your folder path:",
      folder_path
    ))
  }

  con <- DBI::dbConnect(duckdb::duckdb(shared_home = FALSE))

  DBI::dbExecute(con, sprintf("PRAGMA memory_limit='%s'", max_memory))

  DBI::dbExecute(con, "SET enable_progress_bar=false")
  
  # Mount  partitioned genotypes folder
  DBI::dbExecute(
    con,
    sprintf(
      "CREATE VIEW genotypes AS SELECT * FROM read_parquet('%s/**/*.parquet', hive_partitioning = true)",
      geno_path
    )
  )
  
  # Mount the standard flat files
  DBI::dbExecute(
    con,
    sprintf(
      "CREATE VIEW variants AS SELECT * FROM '%s'",
      file.path(folder_path, "variants.parquet")
    )
  )
  DBI::dbExecute(
    con,
    sprintf(
      "CREATE VIEW metadata AS SELECT * FROM '%s'",
      file.path(folder_path, "metadata.parquet")
    )
  )
  DBI::dbExecute(
    con,
    sprintf(
      "CREATE VIEW annotations AS SELECT * FROM '%s'",
      file.path(folder_path, "annotations.parquet")
    )
  )

  # Mount PCIL data  
  pcil_path <- file.path(folder_path, "pcil")
  if (dir.exists(pcil_path)) {
    DBI::dbExecute(
      con,
      sprintf(
        "CREATE VIEW pcil_introgressions AS SELECT * FROM read_parquet('%s/introgressions/**/*.parquet', hive_partitioning = true)",
        pcil_path
      )
    )
    DBI::dbExecute(
      con,
      sprintf(
        "CREATE VIEW pcil_genes AS SELECT * FROM read_parquet('%s/gene_regions/**/*.parquet', hive_partitioning = true)",
        pcil_path
      )
    )

    DBI::dbExecute(
      con,
      sprintf(
        "CREATE VIEW pcil_ibs AS SELECT * FROM read_parquet('%s/ibs_distance/*.parquet')",
        pcil_path
      )
    )
    DBI::dbExecute(
      con,
      sprintf(
        "CREATE VIEW pcil_metadata AS SELECT * FROM read_parquet('%s/sample_metadata.parquet')",
        pcil_path
      )
    )
    DBI::dbExecute(
      con,
      sprintf(
        "CREATE VIEW pcil_genomewide AS SELECT * FROM read_parquet('%s/genomewide_introgressions.parquet')",
        pcil_path
      )
    )

    if (!quiet) {
      message(
        "Successfully connected to the local offline database! Pangenome-scale database  mounted safely."
      )
    }
  } else {
    if (!quiet) {
      message(
        "Successfully connected to the local offline database!  Pangenome-scale database  mounted safely. No folder named pcil."
      )
    }
  }

  return(con)
}




#' Disconnect the local database session
#'
#' @param con A valid DBI connection object generated by \code{connect_local_db()}.
#' @param quiet Logical. If \code{TRUE}, suppresses console messages. Defaults to \code{FALSE}.
#' @return None. Prints a message confirming the disconnection status.
#'
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#' 
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#' 
#' # Establish a virtual connection to the offline database engine
#' con <- connect_local_db(folder_path = my_db_folder, max_memory = "8GB")
#' 
#' # Disconnect at the end of your session
#' disconnect_local_db(con)
#'
#' }
#'
#' @import DBI
#' @export
disconnect_local_db <- function(con, quiet = FALSE) {
  # Check if the connection exists and is currently open
  if (!missing(con) && inherits(con, "DBIConnection") && DBI::dbIsValid(con)) {
    DBI::dbDisconnect(con, shutdown = TRUE)
    if (!quiet) {
      message(
        "Successfully disconnected from the local database. Memory cleared."
      )
    }
  } else {
    if (!quiet) {
      message("The database connection is already closed or invalid.")
    }
  }
}




#' Set the API endpoint URL for your private database 
#'
#' @param url Character. The full URL to your hosted API endpoint
#'   (e.g., "http://rice-genomics.myuniversity.edu:8000").
#'
#' @export
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Set a custom API endpoint URL
#' set_api_url("http://132.145.61.28:8000")
#'
#' }
set_api_url <- function(url) {
  # Strip any accidental trailing slashes
  url <- sub("/$", "", url)

  # Set R options in current session
  options(panGenomeBreedr.api_url = url)

  Sys.setenv(PANGENOME_API_URL = url)

  message("panGenomeBreedr API endpoint successfully set to: ", url)
}



#' Get the current database API endpoint URL
#'
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Get the current API endpoint URL
#' get_api_url()
#'
#' }
#'
#' @returns The character string of the active API URL.
#' @export
get_api_url <- function() {
  # Check if the user set a temporary custom URL in this session
  url <- getOption("panGenomeBreedr.api_url")

  # Check if user set a permanent custom URL in their .Renviron
  if (is.null(url) || url == "") {
    url <- Sys.getenv("PANGENOME_API_URL")
  }

  if (is.null(url) || url == "") {
    tryCatch(
      {
        # Fetch the active endpoint from GitHub 
        github_pointer <- "https://raw.githubusercontent.com/Israel-Tetteh/panGB_Endpoint/main/api_endpoint.txt"

        resp <- httr::GET(github_pointer, httr::timeout(10))
        httr::stop_for_status(resp) 

        txt <- httr::content(resp, as = "text", encoding = "UTF-8")
        url <- trimws(strsplit(txt, "\n", fixed = TRUE)[[1]][1])

        if (is.na(url) || !nzchar(url)) stop("Empty endpoint value")
      },
      error = function(e) {
       # If the github raw file's link fails
        cat('Please ensure you have a stable connection')
      }
    )
  }

  return(url)
}




#' Internal API fetcher
#' @noRd
#' @importFrom jsonlite fromJSON
.api_fetch <- function(endpoint, query = NULL, simplify = TRUE) {
  # Get url , user defined or default
  base_url <- get_api_url()
  url <- paste0(base_url, endpoint)

  # Send the request to the server
  response <- httr::GET(url, query = query)

  # Check for server errors
  if (httr::http_error(response)) {
    stop(
      paste0(
        "API Error [",
        httr::status_code(response),
        "]: Check parameters or server status."
      ),
      call. = FALSE
    )
  }

  # Extract and parse the JSON payload
  raw_json <- httr::content(response, as = "text", encoding = "UTF-8")
  data <- jsonlite::fromJSON(raw_json, simplifyDataFrame = TRUE)

  # Only force into a single dataframe if we are expecting one table
  if (simplify && is.list(data) && !is.data.frame(data)) {
    return(as.data.frame(data))
  }

  return(data)
}





#' List all tables in the database
#'
#' @description
#' This function lists all available tables from either a local database connection
#' or the online database, depending on the selected mode.
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#' @return A character vector of table names in the database.
#'
#' @examples
#' \donttest{
#' # --- Online Mode ---
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # List all tables in the online database
#' online_tables <- list_tables(connect_db_mode = 'online')
#' print(online_tables)
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db",
#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # List tables from the local connection (default mode is 'local')
#' local_tables <- list_tables(con = con_local)
#' # print(local_tables)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
list_tables <- function(
  con = NULL,
  connect_db_mode = c('local', 'online')
) {

  connect_db_mode <- match.arg(connect_db_mode)

  if (connect_db_mode == 'online') {
    return(.api_fetch("/db/tables")) # nocov
  } else {

    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop(
        "A valid 'con' object is required for 'local' mode. Please run connect_local_db() first."
      )
    }
    # Retrieve the list of tables from the database connection
    tables <- DBI::dbListTables(con)
    return(tables)
  }
}





#' Get variant statistics from the database
#'
#' @description
#' Retrieves variant statistics, such as counts and genomic range, grouped by
#' chromosome. This function can operate in two modes: 'local' to query a
#' local database connection, or 'online' to fetch data from the API.
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#' @param include_annotations A logical value indicating whether to include
#'   statistics for the annotations table. Defaults to \code{TRUE}.
#'
#' @return A data frame of variant statistics grouped by chromosome.
#'
#' @examples
#' \donttest{
#' # --- Online Mode ---
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Get variant statistics from the online database, including annotation counts
#' online_stats <- summarize_variants(connect_db_mode = 'online', include_annotations = TRUE)
#' print(online_stats)
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db",
#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Get variant statistics across all chromosomes
#' local_stats <- summarize_variants(con = con_local, include_annotations = TRUE)
#' # print(local_stats)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
summarize_variants <- function(
  con = NULL,
  connect_db_mode = c('local', 'online'),
  include_annotations = TRUE
) {

  connect_db_mode <- match.arg(connect_db_mode)

  if (connect_db_mode == 'online') {
    params <- list(include_annotations = include_annotations)
    return(.api_fetch("/stats/variants", query = params)) # nocov
  } else {
    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop("A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
           call. = FALSE)
    }

    # Extract base statistics from the variants table 
    variant_stats_df <- DBI::dbGetQuery(
      con,
      "
    SELECT
      chrom,
      COUNT(*) AS n_variants,
      MIN(pos) AS min_pos,
      MAX(pos) AS max_pos,
      COUNT(DISTINCT variant_id) AS n_unique_ids
    FROM variants
    GROUP BY chrom
    ORDER BY chrom
    "
    )

    if (include_annotations) {
      # Query for the count of distinct annotated variants using an inner join
      annotation_counts <- DBI::dbGetQuery(
        con,
        "
      SELECT chrom, COUNT(DISTINCT v.variant_id) AS n_annotated
      FROM variants v
      JOIN annotations a ON v.variant_id = a.variant_id
      GROUP BY chrom
      ORDER BY chrom
    "
      )
      # Merge the annotation stats with the base stats
      variant_stats_df <- merge(
        variant_stats_df,
        annotation_counts,
        by = "chrom",
        all.x = TRUE
      )
      # Fill NA values with 0 for chromosomes lacking annotations
      variant_stats_df$n_annotated[is.na(variant_stats_df$n_annotated)] <- 0
    }

    return(variant_stats_df)
  }
}




#' Get summary of database variant impacts by chromosome
#'
#' @description
#' This function summarizes the counts of different variant impact levels (e.g.,
#' HIGH, MODERATE, LOW) for each chromosome and returns the result in a
#' wide-format data frame. It can operate in 'local' or 'online' mode.
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A wide-format data frame where the first column is \code{chrom}, followed by
#'   pivoted columns for each impact type (e.g., \code{impact_HIGH}, \code{impact_MODERATE}),
#'   containing their respective mutation counts.
#'
#' @examples
#' \donttest{
#' # --- Online Mode ---
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Get variant impact summary from the online database
#' online_impact <- summarize_variant_impacts(connect_db_mode = 'online')
#' print(online_impact)
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db",
#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Generate the wide-format impact profile matrix
#' local_impact <- summarize_variant_impacts(con = con_local)
#' # print(local_impact)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
summarize_variant_impacts <- function(
  con = NULL,
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)

  if (connect_db_mode == 'online') {
    return(.api_fetch("/stats/impact")) # nocov
  } else {

    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop("A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
           call. = FALSE)
    }

    # Dynamically pivot the data by counting occurrences of each impact type per chromosome
    query <- "
    PIVOT (
      SELECT v.chrom, a.impact
      FROM annotations a
      JOIN variants v ON a.variant_id = v.variant_id
    )
    ON impact
    USING COUNT(*)
    ORDER BY chrom
  "

    impact_wide <- DBI::dbGetQuery(con, query)
    if (nrow(impact_wide) == 0) {
      return(data.frame())
    }

    # Format column names for clarity 
    col_names <- colnames(impact_wide)
    colnames(impact_wide)[-1] <- paste0("impact_", col_names[-1])

    # Replace any NA with 0 for chromosomes that might be missing a specific impact type entirely
    impact_wide[is.na(impact_wide)] <- 0

    return(impact_wide)
  }
}




#' Get table names and row counts from the database
#'
#' @description
#' Queries the active database to retrieve a list of all mounted tables along
#' with their respective total row counts. It can operate in 'local' or 'online' mode.
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#' @return A data frame containing two columns: \code{table} (the table name)
#'   and \code{n_rows} (the total number of rows in that table).
#'
#' @examples
#' \donttest{
#' # --- Online Mode ---
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Summarize all tables in the online database
#' online_summary <- summarize_database(connect_db_mode = 'online')
#' print(online_summary)
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db",
#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Get row counts for all mounted Parquet views
#' local_summary <- summarize_database(con = con_local)
#' # print(local_summary)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
summarize_database <- function(
  con = NULL,
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)

  # ONLINE MODE
  if (connect_db_mode == 'online') {
    return(.api_fetch("/db/summary")) # nocov
  } else {
  
  # OFFLINE MODE
    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop(
        "A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
        call. = FALSE)
    }

    tables <- DBI::dbListTables(con)
    counts <- sapply(tables, function(tbl) {
      DBI::dbGetQuery(con, sprintf("SELECT COUNT(*) FROM %s", tbl))[[1]]
    })

    return(data.frame(table = tables, n_rows = counts, row.names = NULL))
  }
}




#' Get the genomic range of a candidate gene from a GFF file
#' 
#' @description This function parses a GFF3 file (local or remote) to find the
#' genomic coordinates (chromosome, start, end) for a specified gene ID.
#'
#' @param gene_name A character value indicating the Sobic ID of the candidate gene.
#' @param gff_path A character value specifying the path to the GFF3 file.
#'   URL paths and GZ-compressed files are supported.
#' @returns A list object of three components indicating the chromosome, start
#' and end coordinates of candidate gene.
#' @examples
#' \donttest{
#' # example code
#'
#' # Define path to a remote sorghum GFF3 file (v5.1)
#' gff_path <- "https://raw.githubusercontent.com/awkena/panGB/main/Sbicolor_730_v5.1.gene.gff3.gz"
#' 
#' # Retrieve coordinates for a candidate gene
#' gene_coord_gff(gene_name = "Sobic.005G213600",
#'                gff_path = gff_path)
#'
#' }
#' @export
#' @importFrom R.utils isUrl isGzipped gunzip
gene_coord_gff <- function(gene_name, gff_path) {

  # We handle remote URLs by downloading the file to a temporary location first.
  if (R.utils::isUrl(gff_path)) {
    local_temp <- file.path(tempdir(), basename(gff_path))
    utils::download.file(gff_path, destfile = local_temp, mode = "wb", quiet = TRUE)
    on.exit(if (file.exists(local_temp)) unlink(local_temp), add = TRUE)
    target_path <- local_temp
  } else {
    target_path <- gff_path
  }

  # If the file is compressed, decompress it to a temporary GFF file before reading.
  if (R.utils::isGzipped(target_path)) {
    decompressed_gff <- file.path(tempdir(), "temp_genomic_data.gff3")
    R.utils::gunzip(target_path, destname = decompressed_gff, overwrite = TRUE, remove = FALSE)
    on.exit(if (file.exists(decompressed_gff)) unlink(decompressed_gff), add = TRUE)
    read_from <- decompressed_gff
  } else {
    read_from <- target_path
  }

  # Load the GFF file, skipping headers.
  gff <- utils::read.delim(read_from, comment.char = "#", header = FALSE, sep = "\t", stringsAsFactors = FALSE)

  # Assign standard GFF3 column headers for logical filtering
  colnames(gff) <- c("seqid", "source", "type", "start", "end", "score", "strand", "phase", "attributes")

  # Filter for gene features and extract the name/ID attribute using regex.
  genes <- gff[gff$type == "gene", ]
  genes$extracted_id <- sub(".*(?:ID|Name)=([^;]+).*", "\\1", genes$attributes)

  # Locate the specific gene match
  gmatch <- genes[genes$extracted_id == gene_name, ]

  if (nrow(gmatch) == 0) {
    stop(paste("Gene ID", gene_name, "was not found in the provided GFF file."))
  }

  if (nrow(gmatch) > 1) {
    warning("Multiple gene entries found; returning coordinates for the first occurrence.")
  }

  # Return the genomic range as a structured list
  return(list(
    chrom = gmatch$seqid[1],
    start = as.integer(gmatch$start[1]),
    end = as.integer(gmatch$end[1])
  ))
}





#' Get table schema details
#'
#' @description
#' Retrieves the schema (column names and data types) for a specified table.
#' It can operate in 'local' or 'online' mode.
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param table_name A character value specifying the name of the table to inspect.
#'   Must be one of `"variants"`, `"annotations"`, `"genotypes"`, or `"metadata"`.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A data frame containing the schema details of the target table.
#'
#' @examples
#' \donttest{
#' # --- Online Mode ---
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Get schema for the "variants" table from the online database
#' online_schema <- list_columns(table_name = "variants", connect_db_mode = 'online')
#' print(online_schema)
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db",
#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Inspect the schema of the local "variants" table
#' local_schema <- list_columns(con = con_local, table_name = "variants")
#' # print(local_schema)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
list_columns <- function(
  con = NULL,
  table_name = c("variants", "annotations", "genotypes", "metadata"),
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)
  table_name <- match.arg(table_name)

  if (connect_db_mode == 'online') {
    params <- list(table_name = table_name)
    return(.api_fetch("/db/columns", query = params)) # nocov
  } else {
    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop(
        "A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
        call. = FALSE)
    }
    query <- sprintf("DESCRIBE %s", table_name)
    return(DBI::dbGetQuery(con, query))
  }
}




#' Fetch data from database tables by genomic coordinates
#'
#' @description
#' This function queries variant, annotation, genotype, or metadata tables
#' based on genomic coordinates (chromosome, start, end) or a gene name.
#' It can operate in either 'local' mode (connecting to a local DuckDB database)
#' or 'online' mode (fetching data from a remote API endpoint).
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param table_name A character value specifying the target view to query.
#'   Must be one of `"variants"`, `"annotations"`, `"genotypes"`, or `"metadata"`.
#' @param chrom A character value specifying the target chromosome name (e.g., `"Chr05"`).
#' @param start Integer. Optional start coordinate for the target window region.
#' @param end Integer. Optional end coordinate for the target window region.
#' @param gene_name A character value indicating the specific Sobic gene model ID.
#'   Utilized explicitly when subsetting the `"annotations"` table.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A data frame containing the targeted genomic records. For the `"genotypes"`
#'   table, it returns individual samples unpacked directly into intuitive wide columns,
#'   along with calculated allele metrics.
#'
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # --- Online Mode ---
#' # Query variants table for a specific genomic region from the online database
#' online_variants_data <- fetch_table_region(
#'   table_name = "variants",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'online'
#' )
#' print(head(online_variants_data))
#'
#' # Query genotypes table for the same region from the online database
#' online_genotypes_data <- fetch_table_region(
#'   table_name = "genotypes",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'online'
#' )
#' print(online_genotypes_data[1:6, 1:12])
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db",
#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Extract functional annotations inside a candidate locus region from local DB
#' local_annota_region <- fetch_table_region(
#'   con = con_local,
#'   table_name = "annotations",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   gene_name = "Sobic.005G213600",
#'   connect_db_mode = 'local'
#' )
#' # print(head(local_annota_region))
#'
#' # Extract matrix genotypes within the exact same coordinates window from local DB
#' local_gt_region <- fetch_table_region(
#'   con = con_local,
#'   table_name = "genotypes",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'local'
#' )
#' # print(local_gt_region[1:6, 1:12])
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
fetch_table_region <- function(
  con = NULL,
  table_name = c("variants", "annotations", "genotypes"),
  chrom,
  start = NULL,
  end = NULL,
  gene_name = NULL,
  connect_db_mode = c('local', 'online')
) {
  table_name <- match.arg(table_name)
  connect_db_mode <- match.arg(connect_db_mode)

  if (missing(chrom) || is.null(chrom)) {
    stop(
      "A valid chromosome ('chrom') is required to query locus data.",
      call. = FALSE
    )
  }
  
  if (connect_db_mode == 'online') {
    query_params <- list(
      table_name = table_name,
      chrom = chrom,
      start = start,
      end = end,
      gene_name = gene_name
    )

    result <- .api_fetch("/db/query", query = query_params) # nocov

    if (table_name == 'genotypes') {
      # Reformat to include allele types and frequencies.
      query_result <- append_locus_allele_metrics(region_matrix = result)
      return(query_result)
    } else {
      return(result)
    }
  } else {
    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop(
        "A valid 'con' object is required for 'local' mode. Please run connect_local_db() first."
      )
    }

    # Check if table exists
    all_tables <- DBI::dbListTables(con)
    if (!(table_name %in% all_tables)) {
      stop(sprintf("Table '%s' does not exist in the database.", table_name))
    }

    # ---  Annotations ---
    if (table_name == "annotations") {
      # Create an inner join across the annotations and variants table to filter by chrom and pos
      sql <- "
        SELECT a.*, v.chrom, v.pos
        FROM annotations a
        JOIN variants v ON a.variant_id = v.variant_id
        WHERE v.chrom = ?"

      params <- list(chrom)

      if (!is.null(start) && !is.null(end)) {
        sql <- paste(sql, "AND v.pos BETWEEN ? AND ?")
        params <- append(params, list(start, end))
      }

      # Filter by gene_name
      if (!is.null(gene_name)) {
        sql <- paste(sql, "AND a.gene_name = ?")
        params <- append(params, list(gene_name))
      }

      sql <- paste(sql, "ORDER BY v.pos")
      result <- DBI::dbGetQuery(con, sql, params = params)

      return(result)
    }

    # --- Genotypes ---
    if (table_name == "genotypes") {
      # Dynamically pull columns to safely support both wide and array-packed 'calls' storage formats
      gt_cols <- DBI::dbListFields(con, "genotypes")
      gt_data_cols <- setdiff(gt_cols, c("variant_id", "chrom", "pos"))
      gt_cols_sql <- paste0("g.", gt_data_cols, collapse = ", ")

      sql <- sprintf(
        "
        SELECT g.variant_id, g.chrom, g.pos, v.variant_type, v.ref, v.alt, %s
        FROM genotypes g
        JOIN variants v ON g.variant_id = v.variant_id
        WHERE g.chrom = ?",
        gt_cols_sql
      )

      params <- list(chrom)

      if (!is.null(start) && !is.null(end)) {
        sql <- paste(sql, "AND g.pos BETWEEN ? AND ?")
        params <- append(params, list(start, end))
      }

      sql <- paste(sql, "ORDER BY g.pos")
      result <- DBI::dbGetQuery(con, sql, params = params)

      if (nrow(result) == 0) {
        return(result)
      }

      # Unpack the array
      if ("calls" %in% gt_data_cols && length(gt_data_cols) == 1) {

        parsed_list <- result$calls

        sample_names <- NULL

        # Retrieve sample names from metadata
        if ("metadata" %in% all_tables) {
          sample_metadata <- DBI::dbGetQuery(
            con,
            "SELECT lib FROM metadata ORDER BY array_index ASC"
          )

          # Safely extract the first column 
          if (ncol(sample_metadata) > 0) {
            sample_names <- sample_metadata[[1]]
          }
        }

        if (
          is.null(sample_names) ||
            length(sample_names) != length(parsed_list[[1]])
        ) {
          sample_names <- paste0("Sample_", seq_len(length(parsed_list[[1]])))
        }

        # Reconstruct the matrix to hold all sample calls instantly
        gt_matrix <- do.call(rbind, parsed_list)
        colnames(gt_matrix) <- sample_names

        # Combine the metadata columns with the expanded genotype matrix
        info_cols <- result[, setdiff(names(result), "calls"), drop = FALSE]
        result <- cbind(
          info_cols,
          as.data.frame(gt_matrix, stringsAsFactors = FALSE)
        )
      }

      # Append major/minor allele and freq
      result <- append_locus_allele_metrics(region_matrix = result)
      return(result)

    }

    # --- Variants ---
    # Directly pull and optionally filter variant metadata
    sql <- "
      SELECT * FROM variants v
      WHERE v.chrom = ?"

    params <- list(chrom)

    if (!is.null(start) && !is.null(end)) {
      sql <- paste(sql, "AND v.pos BETWEEN ? AND ?")
      params <- append(params, list(start, end))
    }

    sql <- paste(sql, "ORDER BY v.pos")
    result <- DBI::dbGetQuery(con, sql, params = params)

    return(result)
  }
}




#' Extract variants based on functional mutation impact
#'
#' @description
#' This function extracts variants based on their predicted functional impact
#' (e.g., HIGH, MODERATE, LOW, MODIFIER) within a specified genomic region.
#' It can operate in either 'local' mode (querying a local DuckDB database)
#' or 'online' mode (fetching data from a remote API endpoint).
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param impact_level A character vector specifying the variant impact types to retain.
#'   Allowed classifications are `"HIGH"`, `"MODERATE"`, `"LOW"`, and `"MODIFIER"`.
#' @param chrom A character value specifying the chromosome name (e.g., `"Chr05"`).
#' @param start Integer. Start coordinate for the genomic region.
#' @param end Integer. End coordinate for the genomic region.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A data frame of variants showing their functional impact details
#'   and positional coordinates.
#'
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # --- Online Mode ---
#' # Query for high-impact variants in a specific genomic region from the online database
#' online_high_impact_vars <- fetch_variants_by_impact(
#'   impact_level = "HIGH",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'online'
#' )
#' print(head(online_high_impact_vars))
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db",
#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Extract high-impact variant lines inside a targeted coordinates locus window from local DB
#' local_high_impact_vars <- fetch_variants_by_impact(
#'   con = con_local,
#'   impact_level = "HIGH",
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'local'
#' )
#' # print(head(local_high_impact_vars))
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#'
#' @import DBI
#' @importFrom httr GET content http_error
#' @export
fetch_variants_by_impact <- function(
  con = NULL,
  impact_level = c("HIGH", "MODERATE", "LOW", "MODIFIER"),
  chrom = NULL,
  start = NULL,
  end = NULL,
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)

  if (connect_db_mode == 'online') {
    impact_str <- paste(impact_level, collapse = ",")

    query_params <- list(
      impact_level = impact_str,
      chrom = chrom,
      start = start,
      end = end
    )
    return(.api_fetch("/db/impact", query = query_params)) # nocov
  } else {
    if (is.null(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
      stop("A valid 'con' object is required for 'local' mode. Please run connect_local_db() first.",
           call. = FALSE)
    }

    # Quality check
    allowed <- c("HIGH", "MODERATE", "LOW", "MODIFIER")
    impact_level <- intersect(toupper(impact_level), allowed)

    if (length(impact_level) == 0) {
      stop("No valid impact levels provided.", call. = FALSE)
    }

    # Dynamically build standard SQL IN placeholders
    placeholders <- paste(rep("?", length(impact_level)), collapse = ", ")

    # Join annotations and variants to retrieve requested variants safely via parameterization
    sql <- sprintf(
      "
      SELECT v.*, a.allele, a.annotation, a.impact, a.gene_name,
             a.gene_id, a.feature_type, a.feature_id, a.transcript_biotype,
             a.rank, a.HGVS_c, a.HGVS_p
      FROM variants v
      JOIN annotations a ON v.variant_id = a.variant_id
      WHERE a.impact IN (%s)",
      placeholders
    )
    params <- as.list(impact_level)

    if (!is.null(chrom)) {
      sql <- paste(sql, "AND v.chrom = ?")
      params <- append(params, list(chrom))

      if (!is.null(start) && !is.null(end)) {
        sql <- paste(sql, "AND v.pos BETWEEN ? AND ?")
        params <- append(params, list(start, end))
      }
    }

    sql <- paste(sql, "ORDER BY v.chrom, v.pos")
    result <- DBI::dbGetQuery(con, sql, params = params)

    return(result)
  }
}




#' Compute allele frequencies for a genotype matrix
#' 
#' @param gt A matrix or data frame containing variants (rows) across samples (columns), 
#'   including required variant identification and optional genomic coordinate metadata columns.
#' @param variant_id_col Character. The column name in \code{gt} matching unique variant identifiers. 
#'   Defaults to \code{"variant_id"}.
#' @param chrom_col Character. Optional column name in \code{gt} matching chromosome names. 
#'   Defaults to \code{NULL}.
#' @param pos_col Character. Optional column name in \code{gt} matching genomic positions. 
#'   Defaults to \code{NULL}.
#' 
#' @return A data frame containing unique variant identifiers, optional coordinate tracking columns, 
#'   calculated reference allele frequencies (\code{ref_af}), and alternate allele frequencies (\code{alt_af}).
#' 
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#' 
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#' 
#' # Establish a virtual connection to the offline database engine
#' con <- connect_local_db(folder_path = my_db_folder)
#' 
#' # Pull wide genotype records for a locus window range
#' gt_region <- fetch_table_region(con = con, chrom = "Chr05", start = 75104537, 
#'                       end = 75106403, table_name = "genotypes")
#' 
#' # Compute allele frequencies across all samples in the dataset.
#' af_metrics <- calculate_allele_frequencies(gt_region, variant_id_col = "variant_id", 
#'                       chrom_col = "chrom", pos_col = "pos")
#' 
#' # Disconnect at the end of your session
#' disconnect_local_db(con)
#' }
#' 
#' @export
calculate_allele_frequencies <- function(gt,
                    variant_id_col = 'variant_id',
                    chrom_col = NULL,
                    pos_col = NULL){

  # Exclude non-genotype mapping/reference columns
  sample_cols <- setdiff(colnames(gt), c(variant_id_col, chrom_col, pos_col))
  gt_matrix <- gt[, sample_cols, drop = FALSE]

  # Function to convert GT string to ALT dosage (0, 1, 2)
  parse_gt <- function(gt) {
    if (is.na(gt)) return(NA)
    if (gt %in% c("0|0", "0/0")) return(0)
    if (gt %in% c("0|1", "1|0", "0/1", "1/0")) return(1)
    if (gt %in% c("1|1", "1/1")) return(2)
    return(NA)  
  }

  # Apply conversion function across all sample calls
  dosage_mat <- as.data.frame(apply(gt_matrix, c(1, 2), parse_gt),
                              stringsAsFactors = FALSE)

  # Calculate the alternate allele frequency based on dosages 
  if(nrow(dosage_mat) > 1){
    alt_af <- rowMeans(sapply(dosage_mat, as.numeric), na.rm = TRUE) / 2
  } else{
    # Handle isolated single variant 
    alt_af <- mean(sapply(dosage_mat, as.numeric), na.rm = TRUE) / 2
  }

  # Format the output data frame with IDs and calculated frequencies
  if(is.null(chrom_col) && is.null(pos_col) ) {

    result <- data.frame(variant_id = gt[, variant_id_col], ref_af = 1 - alt_af,
                         alt_af = alt_af)

  } else {

    result <- data.frame(gt[, c(variant_id_col, chrom_col, pos_col)],
                         ref_af = 1 - alt_af,
                         alt_af = alt_af)

  }

  return(result)

}




#' Filter genotypes by allele frequency
#' 
#' @param gt A data frame containing genotype calls queried from the genotypes table.
#' @param variant_id_col Character. The column name in \code{gt} matching unique variant identifiers. 
#'   Defaults to \code{"variant_id"}.
#' @param chrom_col Character. The column name in \code{gt} matching chromosome names. 
#'   Defaults to \code{"chrom"}.
#' @param pos_col Character. The column name in \code{gt} matching genomic positions. 
#'   Defaults to \code{"pos"}.
#' @param min_af Numeric. Minimum alternate allele frequency threshold for filtering. 
#'   Must fall between 0 and 1. Defaults to \code{0}.
#' @param max_af Numeric. Maximum alternate allele frequency threshold for filtering. 
#'   Must fall between 0 and 1. Defaults to \code{1}.
#' 
#' @return A data frame of variants passing the frequency thresholds, tracking their coordinates, 
#'   calculated reference allele frequencies (\code{ref_af}), and alternate allele frequencies (\code{alt_af}).
#' 
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#' 
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db", 
#'                            package = "panGenomeBreedr", 
#'                            mustWork = TRUE)
#' 
#' # Establish a virtual connection to the offline database engine
#' con <- connect_local_db(folder_path = my_db_folder)
#' 
#' # Query genotypes
#' gt_region <- fetch_table_region(con = con, chrom = "Chr05", start = 75104537, 
#'                       end = 75106403, table_name = "genotypes")
#' 
#' filtered_vars <- filter_by_allele_frequency(gt_region, variant_id_col = "variant_id", 
#'                               chrom_col = "chrom", pos_col = "pos", 
#'                               min_af = 0.05, max_af = 0.95)
#' 
#' # Disconnect at the end of your session
#' disconnect_local_db(con)
#' }
#' 
#' @export
filter_by_allele_frequency <- function(gt,
                         variant_id_col = 'variant_id',
                         chrom_col = 'chrom',
                         pos_col = 'pos',
                         min_af = 0,
                         max_af = 1) {

  if (nrow(gt) == 0) {
    stop("No variant found in the genotype matrix.", call. = FALSE)
  }

  result <- calculate_allele_frequencies(gt,
                    variant_id_col = variant_id_col,
                    chrom_col = chrom_col,
                    pos_col = pos_col)

  # Filter by allele frequency
  result <- result[result$alt_af >= min_af & result$alt_af <= max_af, ]

  return(result)
}





#' Fetch variants by allele frequency
#'
#' @description
#' This function queries variants within a specified genomic region and filters
#' them based on a minimum and maximum alternate allele frequency. It can operate
#' in either 'local' mode (querying a local DuckDB database) or 'online' mode
#' (fetching data from a remote API endpoint).
#'
#' @param con A DBI connection object to the local database. Required only when
#'   `connect_db_mode` is 'local'. Defaults to `NULL`.
#' @param min_af Numeric. Minimum alternate allele frequency threshold for filtering.
#'   Must fall between 0 and 1. Defaults to \code{0}.
#' @param max_af Numeric. Maximum alternate allele frequency threshold for filtering.
#'   Must fall between 0 and 1. Defaults to \code{1}.
#' @param chrom A character value specifying the target chromosome name (e.g., \code{"Chr05"}).
#' @param start Integer. Start coordinate for the target window region.
#' @param end Integer. End coordinate for the target window region.
#' @param connect_db_mode A character string specifying the connection mode.
#'   Can be either `'local'` (default) or `'online'`.
#'
#' @return A data frame of variants passing the frequency thresholds within the defined region,
#'   tracking their coordinates, calculated reference allele frequencies (\code{ref_af}),
#'   and alternate allele frequencies (\code{alt_af}).
#'
#' @examples
#' \donttest{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # --- Online Mode ---
#' # Query for common variants (MAF >= 5%) in a specific region from the online database
#' online_common_vars <- fetch_variants_by_allele_frequency(
#'   min_af = 0.05,
#'   max_af = 0.95,
#'   chrom = "Chr05",
#'   start = 75104537,
#'   end = 75106403,
#'   connect_db_mode = 'online'
#' )
#' print(head(online_common_vars))
#'
#' # --- Offline Mode ---
#' # Locate the package example database folder
#' my_db_folder <- system.file("extdata", "pangenome_scale_db",
#'                            package = "panGenomeBreedr",
#'                            mustWork = TRUE)
#'
#' # Establish a virtual connection to the offline database engine
#' con_local <- connect_local_db(folder_path = my_db_folder)
#'
#' # Query a specific locus window and filter for common variants (MAF >= 5%)
#' local_common_vars <- fetch_variants_by_allele_frequency(con = con_local,
#'                                 min_af = 0.05,
#'                                 max_af = 0.95,
#'                                 chrom = "Chr05",
#'                                 start = 75104537,
#'                                 end = 75106403)
#' # print(head(local_common_vars))
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con_local)
#' }
#' @export
fetch_variants_by_allele_frequency <- function(
  con = NULL,
  min_af = 0,
  max_af = 1,
  chrom = NULL,
  start = NULL,
  end = NULL,
  connect_db_mode = c('local', 'online')
) {
  connect_db_mode <- match.arg(connect_db_mode)

  if (is.null(chrom)) {
    stop("Chromosome must be specified.", call. = FALSE)
  }

  # Using fetch_table_region function to extract genotypes table for computation
  gt <- fetch_table_region(
    con = con,
    table_name = "genotypes",
    chrom = chrom,
    start = start,
    end = end,
    connect_db_mode = connect_db_mode
  )

  if (is.null(gt) || nrow(gt) == 0) {
    message("No genotype data found for the specified region.")
    return(data.frame())
  }

  result <- calculate_allele_frequencies(
    gt,
    variant_id_col = 'variant_id',
    chrom_col = 'chrom',
    pos_col = 'pos'
  )

  # Filter by the minimum and maximum allele frequencies
  result <- result[result$alt_af >= min_af & result$alt_af <= max_af, ]

  if (nrow(result) == 0) {
    warning(
      "No variants passed the allele frequency filter. Check your min_af/max_af thresholds.",
      call. = FALSE
    )
  }

  return(result)
}




