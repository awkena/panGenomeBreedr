#' Get variant statistics from the database (local)
#'
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' @param include_annotations A logical value indicating whether to include
#'   statistics for the annotations table. Defaults to \code{TRUE}.
#'
#' @return A data frame of variant statistics grouped by chromosome.
#'
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Define the path to the curated_sorghum_variant_resource folder
#' my_db_folder <- "~/Desktop/curated_sorghum_variant_resource"
#'
#' # Establish the connection
#' con <- connect_local_db(folder_path = "~/Desktop/curated_sorghum_variant_resource")
#'
#' # Get variant statistics across all chromosomes
#' stats_df <- variant_stats(con, include_annotations = TRUE)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con)
#'
#' }
#'
#' @import DBI
#' @export
variant_stats <- function(con, include_annotations = TRUE) {
  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Extract base statistics from the variants table (counts, min/max pos, unique IDs)
  variant_stats <- DBI::dbGetQuery(
    con,
    "
    SELECT
      chrom,
      COUNT(*) AS n_variants,
      MIN(pos) AS min_pos,
      MAX(pos) AS max_pos,
      COUNT(DISTINCT variant_id) AS n_unique_ids
    FROM variants
    GROUP BY chrom
    ORDER BY chrom
  "
  )

  if (include_annotations) {
    # Query for the count of distinct annotated variants using an inner join
    annotation_counts <- DBI::dbGetQuery(
      con,
      "
      SELECT chrom, COUNT(DISTINCT v.variant_id) AS n_annotated
      FROM variants v
      JOIN annotations a ON v.variant_id = a.variant_id
      GROUP BY chrom
      ORDER BY chrom
    "
    )
    # Merge the annotation stats with the base stats
    variant_stats <- merge(
      variant_stats,
      annotation_counts,
      by = "chrom",
      all.x = TRUE
    )
    # Fill NA values with 0 for chromosomes lacking annotations
    variant_stats$n_annotated[is.na(variant_stats$n_annotated)] <- 0
  }

  return(variant_stats)
}




#' Get summary of database variant impacts by chromosome (local)
#'
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#'
#' @return A wide-format data frame where the first column is \code{chrom}, followed by
#'   pivoted columns for each impact type (e.g., \code{impact_HIGH}, \code{impact_MODERATE}),
#'   containing their respective mutation counts.
#'
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Define the path to the curated_sorghum_variant_resource folder
#' my_db_folder <- "~/Desktop/curated_sorghum_variant_resource"
#'
#' # Establish the connection
#' con <- connect_local_db(folder_path = my_db_folder)
#'
#' # Generate the wide-format impact profile matrix
#' impact_matrix <- variant_impact_summary(con)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con)
#'
#' }
#'
#' @import DBI
#' @export
variant_impact_summary <- function(con) {
  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Dynamically pivot the data by counting occurrences of each impact type per chromosome
  query <- "
    PIVOT (
      SELECT v.chrom, a.impact
      FROM annotations a
      JOIN variants v ON a.variant_id = v.variant_id
    )
    ON impact
    USING COUNT(*)
    ORDER BY chrom
  "

  impact_wide <- DBI::dbGetQuery(con, query)
  if (nrow(impact_wide) == 0) {
    return(data.frame())
  }

  # Format column names for clarity (e.g. HIGH -> impact_HIGH)
  col_names <- colnames(impact_wide)
  colnames(impact_wide)[-1] <- paste0("impact_", col_names[-1])

  # Replace any NA with 0 for chromosomes that might be missing a specific impact type entirely
  impact_wide[is.na(impact_wide)] <- 0

  return(impact_wide)
}




#' Get table names and row counts from the database (local)
#'
#' Queries the active local database to instantly retrieve a list of all mounted
#' tables along with their respective total row counts.
#'
#' @param con A DBI connection object to the local database generated by \code{connect_local_db()}.
#' @return A data frame containing two columns: \code{table} (the table name)
#'   and \code{n_rows} (the total number of rows in that table).
#'
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Define the path to the curated_sorghum_variant_resource folder
#' my_db_folder <- "~/Desktop/curated_sorghum_variant_resource"
#'
#' # Establish the connection
#' con <- connect_local_db(folder_path = my_db_folder)
#'
#' # Get row counts for all mounted Parquet views
#' database_summary <- summarize_sqlite_tables(con)
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con)
#' }
#'
#' @import DBI
#' @export
summarize_sqlite_tables <- function(con) {
  if (missing(con) || !inherits(con, "DBIConnection") || !DBI::dbIsValid(con)) {
    stop(
      "Invalid connection. Please run connect_local_db() first and pass the resulting 'con' object."
    )
  }

  # Fetch all available tables
  tables <- DBI::dbListTables(con)

  # Retrieve and store the total number of rows for each table
  counts <- sapply(tables, function(tbl) {
    query <- sprintf("SELECT COUNT(*) FROM %s", tbl)
    DBI::dbGetQuery(con, query)[[1]]
  })

  summary_df <- data.frame(
    table = tables,
    n_rows = counts,
    row.names = NULL
  )

  return(summary_df)
}


#' Get the genomic range of a candidate gene and its features using the Sobic ID from a GFF file (local)
#' @param gene_name A character value indicating the Sobic ID of candidate gene.
#' @param gff_path A character value specifying the path to gff3 file. GZ compressed
#' files and URL file paths are acceptable.
#' @returns A data frame containing the genomic coordinates (chromosome, start, end, strand)
#' of the gene, transcripts, 5'-UTR, CDS, and 3'-UTR.
#' @examples
#' \donttest{
#' # example code
#' library(panGenomeBreedr)
#' # Path to GFF3 file
#' gff_path <- "https://raw.githubusercontent.com/awkena/panGB/main/Sbicolor_730_v5.1.gene.gff3.gz"
#' gene_features <- gene_coord_gff(gene_name = "Sobic.005G213600",
#'                                 gff_path = gff_path)
#' head(gene_features)
#' }
#' @export
#' @importFrom R.utils isUrl isGzipped gunzip
gene_coord_gff <- function(gene_name, gff_path) {

  # Setup strictly unique temporary file paths to prevent namespace collisions
  temp_download <- tempfile(pattern = "dl_", fileext = ".gff3")
  temp_gff <- tempfile(pattern = "extracted_", fileext = ".gff3")

  # Ensure only these specific unique temp files are deleted on exit
  on.exit({
    if (file.exists(temp_download)) unlink(temp_download)
    if (file.exists(temp_gff)) unlink(temp_gff)
  }, add = TRUE)

  # Read GFF
  if (R.utils::isUrl(gff_path)) {
    utils::download.file(gff_path, destfile = temp_download, quiet = TRUE)

    if (R.utils::isGzipped(temp_download)) {
      R.utils::gunzip(temp_download, destname = temp_gff, overwrite = TRUE, remove = FALSE)
      gff <- utils::read.delim(temp_gff, comment.char = "#", header = FALSE, sep = "\t")
    } else {
      gff <- utils::read.delim(temp_download, comment.char = "#", header = FALSE, sep = "\t")
    }

  } else if (R.utils::isGzipped(gff_path)) {
    # Extract local compressed files temporarily without deleting the user's original file
    R.utils::gunzip(gff_path, destname = temp_gff, overwrite = TRUE, remove = FALSE)
    gff <- utils::read.delim(temp_gff, comment.char = "#", header = FALSE, sep = "\t")

  } else {
    gff <- utils::read.delim(gff_path, comment.char = "#", header = FALSE, sep = "\t")
  }

  # Assign standard column names based on the GFF format specifications
  colnames(gff) <- c("seqid", "source", "type", "start", "end", "score", "strand", "phase", "attributes")

  # 1. Identify the core gene
  gene_pattern <- paste0("(ID|Name)=", gene_name, "([;]|$)")
  gff_gene <- gff[gff$type == "gene" & grepl(gene_pattern, gff$attributes), ]

  if (nrow(gff_gene) == 0) stop("Gene not found in GFF.")
  if (nrow(gff_gene) > 1) {
    warning("Multiple gene matches found; using the first match.")
    gff_gene <- gff_gene[1, ]
  }

  # Extract the exact ID to reliably link child features
  gene_id <- sub(".*ID=([^;]+).*", "\\1", gff_gene$attributes)

  # 2. Extract transcripts (mRNAs)
  tx_pattern <- paste0("Parent=", gene_id, "([;]|$)")
  transcripts <- gff[gff$type %in% c("mRNA", "transcript") & grepl(tx_pattern, gff$attributes), ]

  # Initialize list to compile all target features
  results_list <- list()

  # Add the main gene block
  results_list[[1]] <- data.frame(
    ID = gene_id,
    Feature = "gene",
    Chromosome = gff_gene$seqid,
    Start = as.integer(gff_gene$start),
    End = as.integer(gff_gene$end),
    Strand = gff_gene$strand,
    stringsAsFactors = FALSE
  )

  # 3. Process each transcript and its sub-features
  if (nrow(transcripts) > 0) {
    for (i in seq_len(nrow(transcripts))) {
      tx <- transcripts[i, ]
      tx_id <- sub(".*ID=([^;]+).*", "\\1", tx$attributes)

      results_list[[length(results_list) + 1]] <- data.frame(
        ID = tx_id,
        Feature = tx$type,
        Chromosome = tx$seqid,
        Start = as.integer(tx$start),
        End = as.integer(tx$end),
        Strand = tx$strand,
        stringsAsFactors = FALSE
      )

      # Grab all children of this specific transcript (CDS, UTRs, etc.)
      child_pattern <- paste0("Parent=", tx_id, "([;]|$)")
      children <- gff[grepl(child_pattern, gff$attributes), ]

      if (nrow(children) > 0) {
        # Add the raw standard features directly
        results_list[[length(results_list) + 1]] <- data.frame(
          ID = tx_id,
          Feature = children$type,
          Chromosome = children$seqid,
          Start = as.integer(children$start),
          End = as.integer(children$end),
          Strand = children$strand,
          stringsAsFactors = FALSE
        )
      }
    }
  }

  # 4. Collapse and filter to user's desired features
  final_df <- do.call(rbind, results_list)

  target_features <- c("gene", "mRNA", "transcript", "five_prime_UTR", "CDS", "three_prime_UTR")
  final_df <- final_df[final_df$Feature %in% target_features, ]

  # Order logically by ID and Start position for clean downstream parsing
  final_df <- final_df[order(final_df$ID, final_df$Start), ]
  rownames(final_df) <- NULL

  return(final_df)
}


#' Plot the gene model using genomic coordinates (local)
#'
#' @description Visualizes the gene structure with adjusted component heights,
#' a cleaned legend, and a strand orientation arrow. Introns are implicitly
#' represented by the exposed transcript backbone.
#' @param gene_df A data frame containing the genomic coordinates, expected to
#' be the output from \code{gene_coord_gff}.
#' @returns A \code{ggplot} object representing the structural gene model.
#' @examples
#' \donttest{
#' library(panGenomeBreedr)
#' # Path to GFF3 file
#' gff_path <- "https://raw.githubusercontent.com/awkena/panGB/main/Sbicolor_730_v5.1.gene.gff3.gz"
#' gene_features <- gene_coord_gff(gene_name = "Sobic.005G213600",
#'                                 gff_path = gff_path)
#' # Plot gene model for Sobic.005G213600
#' plot_gene_model(gene_df = gene_features)
#' }
#' @export
#' @importFrom ggplot2 ggplot aes geom_rect geom_segment scale_fill_manual theme_minimal labs theme element_blank arrow
#' @importFrom grid unit
plot_gene_model <- function(gene_df) {

  Start <- End <- ymin <- ymax <- Feature <- x_start <- x_end <- NULL

  # 1. Assign geometric heights based on Feature types
  gene_df$ymin <- ifelse(gene_df$Feature == "CDS", -0.15,
                         ifelse(grepl("UTR", gene_df$Feature), -0.075, -0.01))

  gene_df$ymax <- ifelse(gene_df$Feature == "CDS", 0.15,
                         ifelse(grepl("UTR", gene_df$Feature), 0.075, 0.01))

  # 2. Sort the data frame to ensure the backbone is drawn first (bottom layer)
  gene_df <- gene_df[order(gene_df$ymax), ]

  # 3. Extract the backbone to map the strand direction arrow
  backbone <- gene_df[gene_df$Feature %in% c("gene", "mRNA", "transcript"), ]

  # Map arrow coordinates dynamically based on strand (+ points right, - points left)
  if (nrow(backbone) > 0) {
    backbone$x_start <- ifelse(backbone$Strand == "-", backbone$End, backbone$Start)
    backbone$x_end   <- ifelse(backbone$Strand == "-", backbone$Start, backbone$End)
  }

  # 4. Define the clean color palette
  type_colors <- c("five_prime_UTR"  = "#0E77F0", # Light blue
                   "CDS"             = "#FFA500", # orange
                   "three_prime_UTR" = "#009E73", # Green
                   "gene"            = "#999999", # Grey backbone
                   "mRNA"            = "#999999") # Grey fallback

  # 5. Plot the structure
  p <- ggplot2::ggplot() +

    # Draw rectangles for all features with a thin border
    ggplot2::geom_rect(data = gene_df,
                       ggplot2::aes(xmin = Start,
                                    xmax = End,
                                    ymin = ymin,
                                    ymax = ymax,
                                    fill = Feature,
                                    height = 0.01),
                       color = "black", linewidth = 0.3) +

    # Draw the orientation arrow running through the center of the backbone
    ggplot2::geom_segment(data = backbone,
                          ggplot2::aes(x = x_start,
                                       xend = x_end,
                                       y = 0,
                                       yend = 0),
                          arrow = ggplot2::arrow(length = grid::unit(0.1, "inches"),
                                                 type = "closed"),
                          color = "black", linewidth = 0.4) +

    # Map colors AND refine legend
    ggplot2::scale_fill_manual(values = type_colors, name = " ",
                               breaks = c("five_prime_UTR", "CDS", "three_prime_UTR"),
                               labels = c("5' UTR", "CDS", "3' UTR")) +

    ggplot2::theme_classic() +
    ggplot2::labs(x = "Genomic Position (bp)",
                  y = "") +

    # Clean up the y-axis
    ggplot2::theme(axis.line.y = ggplot2::element_blank(),
                   axis.text.y = ggplot2::element_blank(),
                   axis.line.x = ggplot2::element_blank(),
                   axis.ticks.y = ggplot2::element_blank(),
                   panel.grid.minor.y = ggplot2::element_blank(),
                   panel.grid.major.y = ggplot2::element_blank(),
                   panel.grid.minor.x = ggplot2::element_blank(),
                   panel.grid.major.x = ggplot2::element_line(color = "#E5E5E5",
                                                              linetype = "dashed"),
                   legend.position = "bottom")

  return(p)
}


#' Plot genomic variant hotspots (SNPs and INDELs) extracted from the database (local)
#'
#' @description Visualizes variant distributions across a genomic region.
#' Variants are mapped by position, with impact levels determining their
#' vertical placement (lollipop style) and variant types mapped to shapes.
#' @param var_df A data frame containing variant data. Required columns:
#' \code{variant_type} (character: "SNP", "INDEL"), \code{variant_id},
#' and \code{impact} (character: "MODIFIER", "LOW", "MODERATE", "HIGH").
#' @param chrom_col A character string specifying the chromosome column.
#' @param pos_col A character string specifying the variant position column.
#' @param start_pos A numeric integer for the region start. Default is the minimum
#' position in var_df.
#' @param end_pos A numeric integer for the region end. Default is the maximum
#' position in var_df.
#' @returns A \code{ggplot} object representing the variant hotspots.
#' @examples
#' \donttest{
#' library(panGenomeBreedr)
#' # Extract variants within the candidate gene: Sobic.005G213600
#' pg_gt_region <- pg_query_db(table_name = "variants",
#'                             chrom = "Chr05",
#'                             start = 75104537,
#'                             end = 75106403
#'                             )
#'
#' #' # Extract annotations for the candidate gene
#' pg_annota_region <- pg_query_db(table_name = "annotations",
#'                                 chrom = "Chr05",
#'                                 start = 75104537,
#'                                 end = 75106403,
#'                                 gene_name = "Sobic.005G213600"
#'                                 )
#'
#' var_df <- merge(pg_annota_region, pg_gt_region, by = "variant_id")
#'
#' plot_variant_hotspot(var_df)
#' }
#' @export
#' @importFrom ggplot2 ggplot aes geom_hline geom_segment geom_point scale_fill_manual scale_shape_manual scale_x_continuous scale_y_continuous theme_minimal labs theme element_blank element_text element_line guides guide_legend margin
#' @importFrom scales comma
#' @importFrom stats runif
plot_variant_hotspot <- function(var_df,
                                 chrom_col = "chrom.x",
                                 pos_col = "pos.x",
                                 start_pos = NULL,
                                 end_pos = NULL) {

  plot_y <- bae_y <- impact <- variant_type <- NULL

  # 1. Handle missing boundaries dynamically
  if (is.null(start_pos)) start_pos <- min(var_df[[pos_col]], na.rm = TRUE)
  if (is.null(end_pos)) end_pos <- max(var_df[[pos_col]], na.rm = TRUE)

  # 2. Assign base y-coordinates based on Impact levels to stratify them vertically
  var_df$base_y <- ifelse(var_df$impact == "HIGH", 4,
                          ifelse(var_df$impact == "MODERATE", 3,
                                 ifelse(var_df$impact == "LOW", 2, 1)))

  # Add deterministic jitter so the stem drop-lines align perfectly with the points
  set.seed(123)
  var_df$plot_y <- var_df$base_y + stats::runif(nrow(var_df), min = -0.3,
                                                max = 0.3)

  # 3. Calculate summary statistics for the dynamic caption (Fixed typo new_df -> var_df)
  total_vars <- length(unique(var_df$variant_id))
  n_snps <- length(unique(var_df$variant_id[var_df$variant_type == "SNP"]))
  n_indels <- length(unique(var_df$variant_id[var_df$variant_type == "INDEL"]))
  caption_text <- paste0("Total Unique Variants: ", total_vars,
                         " | SNPs: ", n_snps,
                         " | INDELS: ", n_indels)
  # Get chromosome number
  chr <- var_df[[chrom_col]][1]

  # 4. Define specific palettes mapped directly to the requested visual style
  impact_colors <- c("MODIFIER" = "#9A9DA9", # Greyish purple
                     "LOW"      = "#7198EC", # Blue
                     "MODERATE" = "#C98FD9", # Magenta/Purple
                     "HIGH"     = "#F70909") # Red

  type_shapes <- c("SNP"   = 21, # Filled circle (allows color borders)
                   "INDEL" = 24) # Filled triangle up

  # Ensure factor levels so legends are ordered from least to most impact
  var_df$impact <- factor(var_df$impact, levels = c("MODIFIER", "LOW", "MODERATE",
                                                    "HIGH"))

  # 5. Build the plot (Using .data[[]] for tidy evaluation of dynamic column strings)
  plt <- ggplot2::ggplot(var_df, ggplot2::aes(x = .data[[pos_col]])) +

    # Add the thick baseline representing the chromosome track
    ggplot2::geom_hline(yintercept = 0, color = "#C9D4E5", linewidth = 1.2) +

    # Add the stem drop-lines (must be drawn BEFORE points so they sit underneath)
    ggplot2::geom_segment(ggplot2::aes(x = .data[[pos_col]], xend = .data[[pos_col]],
                                       y = 0, yend = plot_y),
                          color = "#E0E0E0", linewidth = 0.3, alpha = 0.6) +

    # Add the variant points with fill mapped to impact, and shape mapped to type
    ggplot2::geom_point(ggplot2::aes(y = plot_y, fill = impact, shape = variant_type),
                        size = 3.5, color = "black", stroke = 0.4, alpha = 0.8) +

    # Map aesthetics explicitly
