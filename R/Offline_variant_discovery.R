#' Generate a combined gene model and variant hotspot overlay plot (local)
#'
#' @description Generates a vertically stacked visualization aligning a structural
#' gene model with its corresponding regional variant hotspots.
#'
#' @details This wrapper function integrates genomic annotations and variant genotypes.
#' It natively queries the pangenome-scale variant relational database. Whether operating
#' in 'online' mode or 'local' mode, it leverages the underlying Parquet and DuckDB
#' architectures optimized for sorghum to efficiently retrieve variants
#' and their snpEff annotations before plotting.
#'
#' @param gene_name A character string indicating the Sobic ID of the candidate gene.
#' @param gff_path A character string specifying the path to the GFF3 file.
#' @param connect_db_mode A character string specifying the database connection mode:
#' either "online" or "local".
#' @param local_db_path A character string specifying the local folder path to the database
#' if running in "local" mode.
#' @param selected_variants An optional character vector of specific `variant_id`s to
#' highlight on the plot with vertical lines, enlarged points, and labels.
#' @param text_sz A numeric value for specifying text size for selected variants.
#'
#' @returns A \code{patchwork} object containing the combined, aligned plots.
#' @examples
#' \donttest{
#' library(panGenomeBreedr)
#' gff_path <- "https://raw.githubusercontent.com/awkena/panGB/main/Sbicolor_730_v5.1.gene.gff3.gz"
#' hotspot_overlay_plot(gene_name = "Sobic.005G213600",
#'                      gff_path = gff_path,
#'                      connect_db_mode = "online",
#'                      selected_variants = c("INDEL_Chr05_75104881", "INDEL_Chr05_75105587"))
#' }
#' @export
#' @importFrom ggplot2 geom_vline geom_point theme element_blank aes scale_y_continuous coord_cartesian
#' @importFrom ggrepel geom_text_repel
#' @importFrom patchwork plot_layout
hotspot_overlay_plot <- function(gene_name,
                                 gff_path,
                                 connect_db_mode = c("online", "local"),
                                 local_db_path = NULL,
                                 selected_variants = NULL,
                                 text_sz = 2.5) {

  # Ensure the connection mode is strictly validated
  connect_db_mode <- match.arg(connect_db_mode)

  # Fail fast: Check for missing local DB path before doing any expensive GFF or DB operations
  if (connect_db_mode == "local" && is.null(local_db_path)) {
    stop("Please provide the path to the local DB.")
  }

  # Get the gene model from the gff3 file
  gene_model <- gene_coord_gff(gene_name = gene_name, gff_path)

  # Plot the gene model
  gene_model_plot <- plot_gene_model(gene_df = gene_model)

  chr <- gene_model$Chromosome[1] # Get chromosome number

  # Get the start pos of the gene
  start_pos <- min(gene_model$Start[gene_model$Feature == "gene"], na.rm = TRUE)

  # Get the end pos of the gene
  end_pos <- max(gene_model$End[gene_model$Feature == "gene"], na.rm = TRUE)

  # Extract variants from DB depending on connection
  if (connect_db_mode == "online") {

    pg_gt_region <- pg_query_db(
      table_name = "variants",
      chrom = chr,
      start = start_pos,
      end = end_pos
    )

    # Extract annotations for the candidate gene
    pg_annota_region <- pg_query_db(
      table_name = "annotations",
      chrom = chr,
      start = start_pos,
      end = end_pos,
      gene_name = gene_name
    )

    var_df <- merge(pg_annota_region, pg_gt_region, by = "variant_id")

  } else {

    # Establish a virtual connection to the offline database engine
    con_demo <- connect_local_db(folder_path = local_db_path)

    # Extract variants within the genomic range of the gene
    gt_region <- query_db(con = con_demo,
                          table_name = "variants",
                          chrom = chr,
                          start = start_pos,
                          end = end_pos)

    #  Query snpEff annotations within a candidate locus gene region
    annota_region <- query_db(con = con_demo,
                              table_name = "annotations",
                              chrom = chr,
                              start = start_pos,
                              end = end_pos,
                              gene_name = gene_name)

    # Merge gt_region and annota_region data frames
    var_df <- merge(annota_region, gt_region, by = "variant_id")
  }

  # Generate the base hotspot plot
  hotspot_plot <- plot_variant_hotspot(var_df,
                                       start_pos = start_pos,
                                       end_pos = end_pos)

  # Remove the x-axis text and title from the top plot so it flows cleanly into the bottom plot
  hotspot_clean <- hotspot_plot +
    ggplot2::theme(axis.title.x = ggplot2::element_blank(),
                   axis.text.x = ggplot2::element_blank(),
                   axis.ticks.x = ggplot2::element_blank())

  # Annotate combined plot to show selected variants
  if (!is.null(selected_variants)) {

    # Filter the dataset for the selected variants
    sel_df <- var_df[var_df$variant_id %in% selected_variants, ]

    if (nrow(sel_df) > 0) {

      #1. Clean the variant labels for plotting (Remove redundant Chr info)
      # This dynamically replaces "_Chr05_" (or whatever 'chr' is) with a space
      sel_df$clean_label <- gsub(paste0("_", chr, "_"), " ", sel_df$variant_id,
                                 ignore.case = TRUE)

      # Replicate the deterministic y-axis mapping used in plot_variant_hotspot
      # so the overlay coordinates perfectly match the underlying plot
      sel_df$base_y <- ifelse(sel_df$impact == "HIGH", 4,
                              ifelse(sel_df$impact == "MODERATE", 3,
                                     ifelse(sel_df$impact == "LOW", 2, 1)))

      # We must replicate the jitter on the FULL df first to match the original seed alignment
      set.seed(123)
      var_df$base_y <- ifelse(var_df$impact == "HIGH", 4,
                              ifelse(var_df$impact == "MODERATE", 3,
                                     ifelse(var_df$impact == "LOW", 2, 1)))
      var_df$plot_y <- var_df$base_y + stats::runif(nrow(var_df), min = -0.3, max = 0.3)

      # Now extract the exactly matched y-coordinates
      sel_df$plot_y <- var_df$plot_y[match(sel_df$variant_id, var_df$variant_id)]


      # 1. Add vertical dotted lines bridging both plots
      hotspot_clean <- hotspot_clean +
        ggplot2::geom_vline(xintercept = sel_df$pos.x, linetype = "dotted", color = "black", alpha = 0.6)

      gene_model_plot <- gene_model_plot +
        ggplot2::geom_vline(xintercept = sel_df$pos.x, linetype = "dotted", color = "black", alpha = 0.6)

      # 3. Expand the y-axis to prevent the nudged coordinates and tall vertical text from being dropped
      suppressMessages({
        hotspot_clean <- hotspot_clean +
          ggplot2::scale_y_continuous(limits = c(-0.2, 7.5)) +
          ggplot2::coord_cartesian(clip = "off")
      })

      # 2. Add enlarged points and names to the hotspot plot
      hotspot_clean <- hotspot_clean +
        ggplot2::geom_point(data = sel_df,
                            ggplot2::aes(x = pos.x, y = plot_y),
                            size = 5, color = "black", shape = 21, stroke = 1) +
        ggrepel::geom_text_repel(data = sel_df,
                                 ggplot2::aes(x = pos.x, y = plot_y, label = clean_label),
                                 size = text_sz,
                                 fontface = "bold",
                                 angle = 90,           # Rotate labels vertically
                                 hjust = 0,            # Anchor text cleanly at the bottom
                                 vjust = 0.5,          # Center align the line to the text base
                                 nudge_y = 0.8,        # Push text upward to clear the plotting space
                                 direction = "x",      # Force ggrepel to only spread them sideways if they overlap
                                 max.overlaps = Inf)   # Force all requested labels to draw
    }
  }

  # Stack them together using patchwork
  # 'heights = c(4, 1)' makes the variant plot 4 times taller than the gene model track
  # 'axes = "collect"' ensures they perfectly align along the Genomic Position
  final_overlay <- hotspot_clean / gene_model_plot +
    patchwork::plot_layout(heights = c(4, 1), axes = "collect")

  # View the final combined plot
  return(final_overlay)
}



