#' Connect to the local offline database
#'
#' @param folder_path Character. The absolute or relative path to the directory
#'   containing the core Parquet files (`genotypes.parquet`, `variants.parquet`,
#'   `metadata.parquet`, `annotations.parquet`).
#' @param max_memory Character. Maximum RAM DuckDB is allowed to utilize.
#'   Defaults to '"8GB"'. Adjust based on system constraints.
#' @param quiet Logical. If \code{TRUE}, suppresses console messages. Defaults to \code{FALSE}.
#'
#' @return A DBI connection object (`con`) linked to the virtual database.
#'
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Define the path to the curated_sorghum_variant_resource folder
#' my_db_folder <- "~/Desktop/curated_sorghum_variant_resource"
#'
#' # Establish the connection
#' con <- connect_local_db(folder_path = my_db_folder, max_memory = "8GB")
#'
#' }
#'
#' @import DBI
#' @export
connect_local_db <- function(folder_path, max_memory = "8GB", quiet = FALSE) {

  expected_files <- c("genotypes.parquet", "variants.parquet",
                      "metadata.parquet", "annotations.parquet")

  for (f in expected_files) {
    full_path <- file.path(folder_path, f)
    if (!file.exists(full_path)) {
      stop(paste("Critical file missing:", f, "\nPlease check your folder path:", folder_path))
    }
  }

  con <- DBI::dbConnect(duckdb::duckdb())

  DBI::dbExecute(con, sprintf("PRAGMA memory_limit='%s'", max_memory))

  # Disable DuckDB progress bar to prevent console spam in Shiny
  DBI::dbExecute(con, "SET enable_progress_bar=false")

  # 4. Create virtual shortcuts (Views) using safe file paths
  DBI::dbExecute(con, sprintf("CREATE VIEW genotypes AS SELECT * FROM '%s'", file.path(folder_path, "genotypes.parquet")))
  DBI::dbExecute(con, sprintf("CREATE VIEW variants AS SELECT * FROM '%s'", file.path(folder_path, "variants.parquet")))
  DBI::dbExecute(con, sprintf("CREATE VIEW metadata AS SELECT * FROM '%s'", file.path(folder_path, "metadata.parquet")))
  DBI::dbExecute(con, sprintf("CREATE VIEW annotations AS SELECT * FROM '%s'", file.path(folder_path, "annotations.parquet")))

  if (!quiet) {
    message("Successfully connected to the local offline database! Virtual views mounted safely.")
  }

  return(con)
}




#' Disconnect the local database session
#'
#' @param con A valid DBI connection object generated by \code{connect_local_db()}.
#' @param quiet Logical. If \code{TRUE}, suppresses console messages. Defaults to \code{FALSE}.
#' @return None. Prints a message confirming the disconnection status.
#'
#' @examples
#' \dontrun{
#' # Load the package
#' library(panGenomeBreedr)
#'
#' # Define the path to the curated_sorghum_variant_resource folder
#' my_db_folder <- "~/Desktop/curated_sorghum_variant_resource"
#'
#' # Establish the connection
#' con <- connect_local_db(folder_path = my_db_folder, max_memory = "8GB")
#'
#' # Disconnect at the end of your session
#' disconnect_local_db(con)
#'
#' }
#'
#' @import DBI
#' @export
disconnect_local_db <- function(con, quiet = FALSE) {
  # Check if the connection exists and is currently open
  if (!missing(con) && inherits(con, "DBIConnection") && DBI::dbIsValid(con)) {
    DBI::dbDisconnect(con, shutdown = TRUE)
    if (!quiet) {
      message(
        "Successfully disconnected from the local database. Memory cleared."
      )
    }
  } else {
    if (!quiet) {
      message("The database connection is already closed or invalid.")
    }
  }
}




